-- 8102 補E（storefront／orders 跨模組；須排在 8007／8008 之後，因為改寫其中三支函式）：
-- 購買會員方案商品（item_type=RP）後自動加入會員方案。只動 groupbuy schema。可重複執行（冪等）。
--
-- 會員方案商品：items.item_type = 'RP'，以 item_royalty_programs（補D #46）指到 royalty_programs（duration_days 空白＝365 天）。
-- 加入（推導；原站送出訂單後流程未擷取）：訂單「已完成」，或「付款完成」（已付 ≥ 訂單金額且已付 > 0）、有會員、不是退貨／換貨／補寄子單，
--   且根訂單（經拆單關聯往上追）建立於 2026-10-29（台灣）之後（避免本功能上線前的舊單被事後補加入）。
--   不加入：草稿、已取消、已刪除、已合併、已拆單、退貨完成。
-- 到期日（與後台「啟動會員方案」一致）：會員目前就是同方案且未到期 → 從原到期日延長「天數 × 數量」；
--   否則（沒有方案、已到期、其他方案）→ 改成此方案，從「參考時間」當天（台灣 23:59:59）起算。
--   參考時間＝第一次加入的時間：取消後還原、合併、拆單重新加入時沿用原本的參考時間，不會因重新加入而多送天數。
-- 帳本 customer_royalty_grants：每張訂單 × 方案最多一筆生效紀錄（部分唯一索引），記錄涵蓋的商品（item_ids）、數量、加入前狀態。
--   同步函式只做「應有」與「已生效」的差異 → 冪等：重複的付款 callback、重複改狀態不會重複延長。
-- 數量（可計入的 RP 明細）：本單明細＋本單「退貨子單（RETURN）／補寄子單（RESHIPMENT）」內的明細（從本單搬過去、仍算客人的），
--   排除明細狀態 RETURNED／RETURNED_NOSALE／CANCELLED（退貨完成、取消）；換貨單（REPLACE，複製的明細）不重複計算。
--   數量增加要「已完成」或付清且有新的付款才補天數；減少隨時扣。
--   退貨／換貨／補寄子單本身不加入，改為同步其主訂單。
-- 撤銷：訂單取消／刪除／退貨完成／已合併／已拆單、改綁其他會員、涵蓋的 RP 明細全部退貨或移除、
--   未付清且（已付低於加入後最高已付〔退款〕或加入時根本沒付款）。
--   追加金額造成的「未付清」不撤銷（已付金額沒有減少）。數量改變 → 在原紀錄補／扣差額天數（不重新起算）。
--   回復方式：會員目前的方案／到期日與帳本鏈一致（沒有被後台手動改過）→ 拿掉這筆（或改數量），從它的「加入前」狀態依序重算之後的生效紀錄；
--   鏈被後台手動改過 → 同方案只扣回／補上這筆的天數，其他方案不動會員（帳本與訂單歷程註明）。
-- 鎖序（全域：訂單 → 庫存 → 會員 → 折扣碼 → 優惠卷 → 優惠條件）：同步一律在訂單之後才鎖會員；
--   沒有 RP 明細也沒有生效紀錄的訂單直接返回、不加任何鎖。
--   結帳（sf_place_order／pos_checkout）：marketing_lock_checkout 在庫存之後、名額之前一併鎖「訂單會員」（原本只鎖折抵點數的會員），
--     core 寫明細（前台）／更新訂單（POS）時觸發的同步只碰已持有的鎖；外層包裝函式與 core 都不改。
--   後台批次改訂單 orders_admin_update：改到 state／total_paid／grand_total／customer_id 時開頭依 id 升冪鎖會員（原本只在取消／刪除）；
--     改到 state 時先以 KEY SHARE 鎖這些訂單商品的庫存列（統計觸發器的外鍵檢查原本在會員之後才取這個鎖，
--     與帶點數折抵的結帳〔庫存 FOR UPDATE → 會員〕可互等，本機壓力測試重現過）；另修正「補一筆只有備註的歷程」被其他觸發器歷程擋掉。
--   合併訂單 orders_join_orders：鎖完全部訂單後先鎖這些訂單的會員，再鎖名額列。
--   退換貨 orders_rr_action（8008 已開頭鎖會員）、付款通知／銀行對帳（單張訂單：訂單 → 會員）不變。

create table if not exists groupbuy.customer_royalty_grants (
  id bigint generated by default as identity primary key,
  tenant_id bigint not null references groupbuy.tenants(id) on delete cascade,
  customer_id bigint not null references groupbuy.customers(id) on delete cascade,
  sales_order_id bigint not null references groupbuy.sales_orders(id) on delete cascade,
  royalty_program_id bigint not null references groupbuy.royalty_programs(id) on delete cascade,
  item_ids bigint[] not null default '{}',              -- 涵蓋的 RP 商品（items.id）；之後改商品綁定不影響已加入的紀錄
  qty integer not null,
  paid_qty integer not null default 0,                  -- 曾經付清的最大數量（退貨申請等暫時減少後回補，不需新的付款）
  duration_days integer not null,                       -- 每份天數（方案無天數 → 365）
  added_days integer not null,                          -- 本筆加上的天數＝duration_days × qty
  paid_amount numeric(14,2) not null default 0,         -- 加入後訂單出現過的最高已付金額（退款判斷）
  ref_at timestamptz not null,                          -- 參考時間（起算日；重新加入沿用第一次的）
  prev_royalty_program_id bigint,                       -- 加入前的會員方案
  prev_expires timestamptz,                             -- 加入前的到期日
  base_at timestamptz not null,                         -- 起算點（延長＝前一個到期日；新加入＝參考時間當天 23:59:59）
  new_expires timestamptz not null,                     -- 加入後的到期日
  granted_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  revoked_at timestamptz,
  revoke_note text
);
