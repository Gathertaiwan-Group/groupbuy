    where o.tenant_id = p_tenant_id and o.id = any(p_ids)
    order by o.id
      for no key update;
  -- 8102：改階段時統計觸發器會以外鍵檢查對商品取 KEY SHARE（原本在會員之後才取）→ 先在會員之前依 id 升冪取同強度的鎖
  --   （與結帳〔庫存 FOR UPDATE → 會員〕不再互等；KEY SHARE 不與其他後台流程的 NO KEY UPDATE 衝突）
  if p_patch ? 'state' then
    perform 1 from groupbuy.items i
      where i.tenant_id = p_tenant_id
        and i.id in (select l.item_id from groupbuy.order_items l
                      where l.tenant_id = p_tenant_id and l.sales_order_id = any(p_ids) and l.item_id is not null
                     union
                     select i2.parent_item_id from groupbuy.order_items l
                       join groupbuy.items i2 on i2.id = l.item_id and i2.tenant_id = l.tenant_id
                      where l.tenant_id = p_tenant_id and l.sales_order_id = any(p_ids)
                        and i2.share_stock and i2.parent_item_id is not null)
      order by i.id
        for key share;
  end if;
  -- 8102：改到階段／已付金額／訂單金額／會員時也先鎖會員（會員方案 8102、回饋點數 6008 的觸發器會改會員）
  if coalesce(p_patch->>'state', '') in ('CANCELED', 'DELETED') or p_patch ?| array['state', 'total_paid', 'grand_total', 'customer_id'] then
    perform 1 from groupbuy.customers c
      where c.tenant_id = p_tenant_id
        and c.id in (select o.customer_id from groupbuy.sales_orders o
                      where o.tenant_id = p_tenant_id and o.id = any(p_ids) and o.customer_id is not null
                     union
                     select nullif(p_patch->>'customer_id', '')::bigint)
      order by c.id
        for no key update;
  end if;
  select coalesce(max(h.id), 0) into v_max
    from groupbuy.sales_order_histories h
   where h.tenant_id = p_tenant_id and h.sales_order_id = any(p_ids);
  return query
    update groupbuy.sales_orders t
       set (
         group_buy_id, customer_id, state, status, action, grand_total, shipping_amount, extra_fee, cod_fee,
         discount_amount, points_used, total_paid, internal_shipping_amount, commission_amount, payment_method,
         virtual_bank_account, credit_card_number, store_payment_code, date_paid, date_payment_due,
         date_shipped, date_expected_shipping, date_einvoice, date_last_sms, date_canceled, date_completed,
         deliver_time, shipping_type, shipping_provider, shipping_receipt_number, shipping_tag,
         flat_rate_shipping_id, pickup_store_id, invoice_number, note, staff_note, log, blacklist_note,
         customer_firstname, customer_email, customer_telephone, customer_ip, customer_user_agent, ref_code,
         coupon_code, api_user_data, apidata, cvsmap_response, contain_back_orders, billing_fb_nickname,
         billing_birthday, billing_country, billing_city, billing_postcode, billing_district, billing_street,
         billing_receipt_type, billing_receipt_title, billing_receipt_vat_id, billing_receipt_paper,
         billing_receipt_donate, billing_receipt_donation_code, billing_receipt_carrier_type,
         billing_receipt_carrier_num, billing_bank_name, billing_bank_account, billing_installment,
         shipping_firstname, shipping_telephone, shipping_email, shipping_country, shipping_city,
         shipping_postcode, shipping_district, shipping_street, shipping_oversea, shipping_island, cvs_type,
         cvs_store_id, cvs_store_name, cvs_address, preferred_delivery_dates
       ) = (
         select
           r.group_buy_id, r.customer_id, r.state, r.status, r.action, r.grand_total, r.shipping_amount,
           r.extra_fee, r.cod_fee, r.discount_amount, r.points_used, r.total_paid, r.internal_shipping_amount,
           r.commission_amount, r.payment_method, r.virtual_bank_account, r.credit_card_number,
           r.store_payment_code, r.date_paid, r.date_payment_due, r.date_shipped, r.date_expected_shipping,
           r.date_einvoice, r.date_last_sms, r.date_canceled, r.date_completed, r.deliver_time,
           r.shipping_type, r.shipping_provider, r.shipping_receipt_number, r.shipping_tag,
           r.flat_rate_shipping_id, r.pickup_store_id, r.invoice_number, r.note, r.staff_note, r.log,
           r.blacklist_note, r.customer_firstname, r.customer_email, r.customer_telephone, r.customer_ip,
           r.customer_user_agent, r.ref_code, r.coupon_code, r.api_user_data, r.apidata, r.cvsmap_response,
           r.contain_back_orders, r.billing_fb_nickname, r.billing_birthday, r.billing_country, r.billing_city,
           r.billing_postcode, r.billing_district, r.billing_street, r.billing_receipt_type,
           r.billing_receipt_title, r.billing_receipt_vat_id, r.billing_receipt_paper,
           r.billing_receipt_donate, r.billing_receipt_donation_code, r.billing_receipt_carrier_type,
           r.billing_receipt_carrier_num, r.billing_bank_name, r.billing_bank_account, r.billing_installment,
           r.shipping_firstname, r.shipping_telephone, r.shipping_email, r.shipping_country, r.shipping_city,
           r.shipping_postcode, r.shipping_district, r.shipping_street, r.shipping_oversea, r.shipping_island,
           r.cvs_type, r.cvs_store_id, r.cvs_store_name, r.cvs_address, r.preferred_delivery_dates
           from jsonb_populate_record(t, coalesce(p_patch, '{}'::jsonb)) r
       )
     where t.tenant_id = p_tenant_id and t.id = any(p_ids)
    returning t.id;
  if coalesce(p_note, '') <> '' then
    update groupbuy.sales_order_histories h
       set note = p_note
     where h.tenant_id = p_tenant_id and h.sales_order_id = any(p_ids) and h.id > v_max and h.note is null;
    -- 沒有狀態變動（觸發器未寫歷程）的訂單：補一筆只有備註的歷程（金額重算、改地址…也看得到操作紀錄）
    insert into groupbuy.sales_order_histories (tenant_id, sales_order_id, actor, admin_user_id, note)
    select p_tenant_id, o.id, coalesce(nullif(p_actor, ''), 'ADMIN'), p_admin_user_id, p_note
      from groupbuy.sales_orders o
     where o.tenant_id = p_tenant_id and o.id = any(p_ids)
       -- 8102：只看「帶這次備註」的新歷程（會員方案等觸發器自己寫的歷程有內容，不可擋掉這次的備註）
       and not exists (select 1 from groupbuy.sales_order_histories h
                        where h.tenant_id = p_tenant_id and h.sales_order_id = o.id and h.id > v_max and h.note = p_note);
  end if;
end $$;


-- ───────────── 鎖序：合併訂單（8007 orders_join_orders 只加「訂單之後鎖會員」；回傳型別不變） ─────────────
create or replace function groupbuy.orders_join_orders(p_tenant_id bigint, p_admin_user_id bigint, p_groups jsonb)
returns jsonb
language plpgsql
set search_path = groupbuy, pg_temp
as $$
declare
  g jsonb;
  v_pid bigint;
  v_kids bigint[];
  v_all bigint[];
  v_n integer;
  v_seq integer;
  v_puuid text;
  v_kuuids text;
  a record;
  v_out jsonb := '[]'::jsonb;
  v_every bigint[];
  v_comp bigint[];
begin
  if p_tenant_id is null or p_groups is null or jsonb_typeof(p_groups) <> 'array' then
    raise exception using errcode = 'P0001', message = 'ORD_JOIN_BAD_INPUT';
  end if;
  -- 8007：開頭一次依全域順序取得全部鎖：所有組的訂單（id 升冪）→ 所有相連訂單帳本牽涉的名額列（折扣碼 → 優惠卷 → 優惠條件）。
  -- 之後逐組搬移、改子單階段（觸發器）都只會碰已持有的鎖，不在交易中途追加名額列的鎖。
  select coalesce(array_agg(distinct v order by v), '{}') into v_every
    from (select nullif(x->>'parentId', '')::bigint as v
            from jsonb_array_elements(p_groups) x
          union all
          select nullif(c #>> '{}', '')::bigint
            from jsonb_array_elements(p_groups) x
            cross join lateral jsonb_array_elements(case when jsonb_typeof(x->'childIds') = 'array' then x->'childIds' else '[]'::jsonb end) c) s
   where v is not null;
  perform 1 from groupbuy.sales_orders where tenant_id = p_tenant_id and id = any(v_every) order by id for update;
  -- 8102：訂單之後、名額列之前鎖這些訂單的會員（id 升冪）；子單改「已合併」時會員方案／回饋點數觸發器會改會員
  perform 1 from groupbuy.customers c
   where c.tenant_id = p_tenant_id
     and c.id in (select o.customer_id from groupbuy.sales_orders o
                   where o.tenant_id = p_tenant_id and o.id = any(v_every) and o.customer_id is not null)
   order by c.id
     for no key update;
  select coalesce(array_agg(distinct c.id order by c.id), '{}') into v_comp
    from unnest(v_every) o(id)
    cross join lateral groupbuy.marketing_usage_component(p_tenant_id, o.id) as c(id);
  perform groupbuy.marketing_lock_usage_refs(p_tenant_id, v_comp);

  for g in select x from jsonb_array_elements(p_groups) x loop
    v_pid := nullif(g->>'parentId', '')::bigint;
    select coalesce(array_agg(distinct v), '{}') into v_kids
      from (select nullif(x #>> '{}', '')::bigint as v
              from jsonb_array_elements(case when jsonb_typeof(g->'childIds') = 'array' then g->'childIds' else '[]'::jsonb end) x) s
     where v is not null and v <> v_pid;
    if v_pid is null or cardinality(v_kids) = 0 then
      raise exception using errcode = 'P0001', message = 'ORD_JOIN_BAD_INPUT';
    end if;
    v_all := v_kids || v_pid;

    perform 1 from groupbuy.sales_orders where tenant_id = p_tenant_id and id = any(v_all) order by id for update;
    select count(*)::integer into v_n
      from groupbuy.sales_orders
     where tenant_id = p_tenant_id and id = any(v_all) and state = 'PROCESSING'
       and status not in ('SEND_ORDER_EMAIL', 'SEND_PAID_EMAIL', 'SEND_SHIPPING_EMAIL', 'SEND_EINVOICE');
    if v_n <> cardinality(v_all) then
      raise exception using errcode = 'P0001', message = 'ORD_JOIN_STATE:' || v_pid;
    end if;
    select uuid into v_puuid from groupbuy.sales_orders where id = v_pid and tenant_id = p_tenant_id;

    -- 商品搬到母單（接續序號）
    select coalesce(max(seq), 0) into v_seq from groupbuy.order_items where tenant_id = p_tenant_id and sales_order_id = v_pid;
    with m as (
      select id, row_number() over (order by seq, id) as rn
        from groupbuy.order_items where tenant_id = p_tenant_id and sales_order_id = any(v_kids)
    )
    update groupbuy.order_items o set sales_order_id = v_pid, seq = v_seq + m.rn::integer
      from m where o.id = m.id;

    -- 相同商品（同商品、預購、單價、贈品、規格、備註）合併為一列（組合商品不合併）
    with k as (
      select id,
             first_value(id) over (
               partition by item_id, back_order, price, gift, coalesce(specifications_label, ''), coalesce(attribute_note, '')
               order by seq, id) as keep_id
        from groupbuy.order_items
       where tenant_id = p_tenant_id and sales_order_id = v_pid and not bundle_root and not bundle_child and item_id is not null
    ), s as (
      select k.keep_id, sum(o.total)::integer as t, sum(o.discount) as d, sum(o.amount) as a
        from k join groupbuy.order_items o on o.id = k.id
       group by k.keep_id
      having count(*) > 1
    ), upd as (
      update groupbuy.order_items o set total = s.t, discount = s.d, amount = s.a
        from s where o.id = s.keep_id
      returning o.id
    )
    delete from groupbuy.order_items d
     using k
     where d.id = k.id and k.id <> k.keep_id;

    -- 優惠明細與名額帳本
    update groupbuy.sales_order_coupons set sales_order_id = v_pid where tenant_id = p_tenant_id and sales_order_id = any(v_kids);
    update groupbuy.sales_order_sales_rules set sales_order_id = v_pid where tenant_id = p_tenant_id and sales_order_id = any(v_kids);
    perform groupbuy.marketing_merge_order_usage(p_tenant_id, v_pid, v_kids);

    -- 母單金額
    select sum(coalesce(grand_total, 0)) - sum(case when id = v_pid then 0 else coalesce(shipping_amount, 0) + coalesce(cod_fee, 0) end) as grand,
           sum(coalesce(total_paid, 0)) as paid,
           sum(coalesce(discount_amount, 0)) as disc,
           sum(coalesce(extra_fee, 0)) as extra,
           string_agg(note, E'\n' order by created_at, id) filter (where btrim(coalesce(note, '')) <> '') as note,
           string_agg(staff_note, E'\n' order by created_at, id) filter (where btrim(coalesce(staff_note, '')) <> '') as staff_note,
           string_agg(uuid, '、' order by created_at, id) filter (where id <> v_pid) as kid_uuids
      into a
      from groupbuy.sales_orders where tenant_id = p_tenant_id and id = any(v_all);
    v_kuuids := a.kid_uuids;
    perform groupbuy.orders_admin_update(
      p_tenant_id, array[v_pid]::bigint[],
      jsonb_build_object('grand_total', a.grand, 'total_paid', a.paid, 'discount_amount', a.disc, 'extra_fee', a.extra,
                         'note', a.note, 'staff_note', a.staff_note),
      p_admin_user_id, '合併訂單：' || coalesce(v_kuuids, ''), 'ADMIN');

    -- 關聯先建（子單改已合併時，名額歸屬即可依母單判斷），再改子單階段
    insert into groupbuy.sales_order_relations (tenant_id, parent_sales_order_id, sales_order_id, relation, is_done)
    select p_tenant_id, v_pid, k, 'COMBINE', true from unnest(v_kids) k;
    perform groupbuy.orders_admin_update(
      p_tenant_id, v_kids, jsonb_build_object('state', 'COMBINED'), p_admin_user_id, '已合併至訂單 ' || coalesce(v_puuid, ''), 'ADMIN');

    v_out := v_out || jsonb_build_array(jsonb_build_object('parentId', v_pid, 'childIds', to_jsonb(v_kids)));
  end loop;
  return v_out;
end
$$;



