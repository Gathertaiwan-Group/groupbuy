-- 台灣時間當天 23:59:59
create or replace function groupbuy.sf_royalty_day_end(p_at timestamptz)
returns timestamptz
language sql
stable
set search_path = groupbuy, pg_temp
as $$
  select ((date_trunc('day', p_at at time zone 'Asia/Taipei') + interval '1 day' - interval '1 second') at time zone 'Asia/Taipei')
$$;

-- 會員目前的方案／到期日是否等於帳本鏈的結果（每筆的「加入前」＝前一筆的「加入後」，最後一筆＝會員目前值）
create or replace function groupbuy.sf_royalty_chain_intact(p_tenant_id bigint, p_customer_id bigint)
returns boolean
language plpgsql
stable
set search_path = groupbuy, pg_temp
as $$
declare
  c record;
  h record;
  v_has boolean := false;
  v_prog bigint;
  v_exp timestamptz;
begin
  select royalty_program_id, date_royalty_program_expires into c
    from groupbuy.customers where id = p_customer_id and tenant_id = p_tenant_id;
  if not found then
    return false;
  end if;
  for h in
    select royalty_program_id, prev_royalty_program_id, prev_expires, new_expires
      from groupbuy.customer_royalty_grants
     where customer_id = p_customer_id and tenant_id = p_tenant_id and revoked_at is null
     order by id
  loop
    if v_has then
      if h.prev_royalty_program_id is distinct from v_prog or h.prev_expires is distinct from v_exp then
        return false;
      end if;
    end if;
    v_has := true;
    v_prog := h.royalty_program_id;
    v_exp := h.new_expires;
  end loop;
  if not v_has then
    return true;
  end if;
  return c.royalty_program_id is not distinct from v_prog and c.date_royalty_program_expires is not distinct from v_exp;
end
$$;

-- 從 p_from_id（含）起依序重算會員的生效紀錄，第一筆的「加入前」＝(p_prog, p_exp)，最後寫回會員（沒有紀錄＝會員改回 p_prog/p_exp）
create or replace function groupbuy.sf_royalty_rechain(p_tenant_id bigint, p_customer_id bigint, p_from_id bigint, p_prog bigint, p_exp timestamptz)
returns void
language plpgsql
set search_path = groupbuy, pg_temp
as $$
declare
  h record;
  v_prog bigint := p_prog;
  v_exp timestamptz := p_exp;
  v_base timestamptz;
begin
  for h in
    select id, royalty_program_id, ref_at, added_days
      from groupbuy.customer_royalty_grants
     where customer_id = p_customer_id and tenant_id = p_tenant_id and revoked_at is null and id >= coalesce(p_from_id, 0)
     order by id
       for update
  loop
    if v_prog = h.royalty_program_id and v_exp is not null and v_exp > h.ref_at then
      v_base := v_exp;
    else
      v_base := groupbuy.sf_royalty_day_end(h.ref_at);
    end if;
    update groupbuy.customer_royalty_grants
       set prev_royalty_program_id = v_prog, prev_expires = v_exp, base_at = v_base,
           new_expires = v_base + make_interval(days => h.added_days), updated_at = now()
     where id = h.id;
    v_prog := h.royalty_program_id;
    v_exp := v_base + make_interval(days => h.added_days);
  end loop;
  update groupbuy.customers
     set royalty_program_id = v_prog, date_royalty_program_expires = v_exp, updated_at = now()
   where id = p_customer_id and tenant_id = p_tenant_id
     and (royalty_program_id is distinct from v_prog or date_royalty_program_expires is distinct from v_exp);
end
$$;

-- 加入（呼叫端已持有訂單與會員的鎖）
create or replace function groupbuy.sf_royalty_grant_apply(p_tenant_id bigint, p_customer_id bigint, p_order_id bigint, p_program_id bigint,
                                                           p_item_ids bigint[], p_qty integer, p_days integer, p_paid numeric, p_ref_at timestamptz)
returns void
language plpgsql
set search_path = groupbuy, pg_temp
as $$
declare
  c record;
  v_days integer := case when coalesce(p_days, 0) > 0 then p_days else 365 end;
  v_added integer;
  v_base timestamptz;
  v_new timestamptz;
  v_title text;
begin
  if p_customer_id is null or p_program_id is null or coalesce(p_qty, 0) <= 0 then
    return;
  end if;
  select id, royalty_program_id, date_royalty_program_expires into c
    from groupbuy.customers where id = p_customer_id and tenant_id = p_tenant_id for no key update;
  if not found then
    return;
  end if;
  v_added := v_days * p_qty;
  if c.royalty_program_id = p_program_id and c.date_royalty_program_expires is not null and c.date_royalty_program_expires > p_ref_at then
    v_base := c.date_royalty_program_expires;
  else
    v_base := groupbuy.sf_royalty_day_end(p_ref_at);
  end if;
  v_new := v_base + make_interval(days => v_added);
  insert into groupbuy.customer_royalty_grants (tenant_id, customer_id, sales_order_id, royalty_program_id, item_ids, qty, paid_qty, duration_days, added_days,
                                                paid_amount, ref_at, prev_royalty_program_id, prev_expires, base_at, new_expires)
  values (p_tenant_id, p_customer_id, p_order_id, p_program_id, coalesce(p_item_ids, '{}'), p_qty, p_qty, v_days, v_added,
          coalesce(p_paid, 0), p_ref_at, c.royalty_program_id, c.date_royalty_program_expires, v_base, v_new);
  update groupbuy.customers
     set royalty_program_id = p_program_id, date_royalty_program_expires = v_new, updated_at = now()
   where id = p_customer_id and tenant_id = p_tenant_id;
  select title into v_title from groupbuy.royalty_programs where id = p_program_id;
  insert into groupbuy.sales_order_histories (tenant_id, sales_order_id, actor, note)
  values (p_tenant_id, p_order_id, 'SYSTEM',
          '[會員方案] 已加入「' || coalesce(v_title, '') || '」' || v_added || ' 天，到期日 '
          || to_char(v_new at time zone 'Asia/Taipei', 'YYYY-MM-DD'));
end
$$;

-- 撤銷一筆生效中的紀錄（呼叫端已持有訂單與會員的鎖）
create or replace function groupbuy.sf_royalty_grant_revoke(p_grant_id bigint, p_reason text, p_history boolean default true)
returns void
language plpgsql
set search_path = groupbuy, pg_temp
as $$
declare
  g record;
  c record;
  v_next bigint;
  v_note text;
  v_title text;
begin
  select * into g from groupbuy.customer_royalty_grants where id = p_grant_id and revoked_at is null for update;
  if not found then
    return;
  end if;
  select id, royalty_program_id, date_royalty_program_expires into c
    from groupbuy.customers where id = g.customer_id and tenant_id = g.tenant_id for no key update;
  if not found then
    v_note := '會員已不存在';
  elsif groupbuy.sf_royalty_chain_intact(g.tenant_id, g.customer_id) then
    update groupbuy.customer_royalty_grants set revoked_at = now(), updated_at = now() where id = g.id;
    select min(id) into v_next from groupbuy.customer_royalty_grants
     where customer_id = g.customer_id and tenant_id = g.tenant_id and revoked_at is null and id > g.id;
    if v_next is null then
      update groupbuy.customers
         set royalty_program_id = g.prev_royalty_program_id, date_royalty_program_expires = g.prev_expires, updated_at = now()
       where id = c.id and tenant_id = g.tenant_id;
    else
      perform groupbuy.sf_royalty_rechain(g.tenant_id, g.customer_id, v_next, g.prev_royalty_program_id, g.prev_expires);
    end if;
    select royalty_program_id, date_royalty_program_expires into c from groupbuy.customers where id = c.id;
    v_note := case when c.royalty_program_id is null then '已回復為無會員方案'
                   else '會員方案到期日重算為 ' || to_char(c.date_royalty_program_expires at time zone 'Asia/Taipei', 'YYYY-MM-DD') end;
  elsif c.royalty_program_id = g.royalty_program_id and c.date_royalty_program_expires is not null then
    update groupbuy.customers
       set date_royalty_program_expires = date_royalty_program_expires - make_interval(days => g.added_days), updated_at = now()
     where id = c.id and tenant_id = g.tenant_id;
    v_note := '會員方案曾在後台變更，只扣回 ' || g.added_days || ' 天';
  else
    v_note := '會員方案已改為其他方案，未回復';
  end if;
  update groupbuy.customer_royalty_grants
     set revoked_at = coalesce(revoked_at, now()), updated_at = now(), revoke_note = left(coalesce(p_reason, '') || '：' || v_note, 500)
   where id = g.id;
  if p_history then
    select title into v_title from groupbuy.royalty_programs where id = g.royalty_program_id;
    insert into groupbuy.sales_order_histories (tenant_id, sales_order_id, actor, note)
    values (g.tenant_id, g.sales_order_id, 'SYSTEM', '[會員方案] 撤銷「' || coalesce(v_title, '') || '」' || g.added_days || ' 天（' || coalesce(p_reason, '') || '）：' || v_note);
  end if;
end
$$;

-- 改數量／涵蓋商品（呼叫端已持有訂單與會員的鎖）：補／扣差額天數，不重新起算
create or replace function groupbuy.sf_royalty_grant_adjust(p_grant_id bigint, p_qty integer, p_item_ids bigint[])
returns void
language plpgsql
set search_path = groupbuy, pg_temp
as $$
declare
  g record;
  c record;
  v_delta integer;
  v_note text;
  v_title text;
begin
  select * into g from groupbuy.customer_royalty_grants where id = p_grant_id and revoked_at is null for update;
  if not found or coalesce(p_qty, 0) <= 0 then
    return;
  end if;
  if p_qty = g.qty and coalesce(p_item_ids, '{}') = g.item_ids then
    return;
  end if;
  v_delta := (p_qty - g.qty) * g.duration_days;
  select id, royalty_program_id, date_royalty_program_expires into c
    from groupbuy.customers where id = g.customer_id and tenant_id = g.tenant_id for no key update;
  if not found then
    update groupbuy.customer_royalty_grants set qty = p_qty, item_ids = coalesce(p_item_ids, '{}'), added_days = duration_days * p_qty, updated_at = now() where id = g.id;
    return;
  end if;
  if groupbuy.sf_royalty_chain_intact(g.tenant_id, g.customer_id) then
    update groupbuy.customer_royalty_grants
       set qty = p_qty, item_ids = coalesce(p_item_ids, '{}'), added_days = duration_days * p_qty, updated_at = now()
     where id = g.id;
    perform groupbuy.sf_royalty_rechain(g.tenant_id, g.customer_id, g.id, g.prev_royalty_program_id, g.prev_expires);
    v_note := '重算';
  elsif c.royalty_program_id = g.royalty_program_id and c.date_royalty_program_expires is not null then
    update groupbuy.customers
       set date_royalty_program_expires = date_royalty_program_expires + make_interval(days => v_delta), updated_at = now()
     where id = c.id and tenant_id = g.tenant_id;
    update groupbuy.customer_royalty_grants
       set qty = p_qty, item_ids = coalesce(p_item_ids, '{}'), added_days = duration_days * p_qty,
           new_expires = new_expires + make_interval(days => v_delta), updated_at = now()
     where id = g.id;
    v_note := '會員方案曾在後台變更，只調整天數';
  else
    update groupbuy.customer_royalty_grants
       set qty = p_qty, item_ids = coalesce(p_item_ids, '{}'), added_days = duration_days * p_qty, updated_at = now()
     where id = g.id;
    v_note := '會員方案已改為其他方案，未調整會員';
  end if;
  if v_delta <> 0 then
    select title into v_title from groupbuy.royalty_programs where id = g.royalty_program_id;
    select royalty_program_id, date_royalty_program_expires into c from groupbuy.customers where id = c.id;
    insert into groupbuy.sales_order_histories (tenant_id, sales_order_id, actor, note)
    values (g.tenant_id, g.sales_order_id, 'SYSTEM',
            '[會員方案] 「' || coalesce(v_title, '') || '」數量 ' || g.qty || ' → ' || p_qty || '（' || case when v_delta > 0 then '+' else '' end || v_delta || ' 天，'
            || v_note || '），目前到期日 ' || coalesce(to_char(c.date_royalty_program_expires at time zone 'Asia/Taipei', 'YYYY-MM-DD'), '—'));
  end if;
end
$$;

-- 依訂單目前狀態同步會員方案（冪等）
create or replace function groupbuy.sf_sync_order_membership(p_tenant_id bigint, p_order_id bigint)
returns void
language plpgsql
set search_path = groupbuy, pg_temp
as $$
declare
  o record;
  r record;
  g record;
  v_items jsonb := '{}'::jsonb;     -- {items.id: 可計入數量}
  v_keep boolean;
  v_grant boolean;
  v_qty integer;
  v_reason text;
  v_covered bigint[];
  v_ref timestamptz;
  v_root timestamptz;
begin
  if p_tenant_id is null or p_order_id is null then
    return;
  end if;
  -- 沒有 RP 明細、也沒有生效紀錄 → 不處理、不加鎖（絕大多數訂單）
  if not exists (select 1 from groupbuy.customer_royalty_grants where sales_order_id = p_order_id and tenant_id = p_tenant_id and revoked_at is null)
     and not exists (select 1
                       from groupbuy.order_items oi
                       join groupbuy.items i on i.id = oi.item_id and i.tenant_id = oi.tenant_id and i.item_type = 'RP'
                      where oi.sales_order_id = p_order_id and oi.tenant_id = p_tenant_id) then
    return;
  end if;
  -- 退貨／換貨／補寄子單：不自己加入，改同步主訂單（退貨申請中的明細算主訂單的）
  if exists (select 1 from groupbuy.sales_order_relations
              where tenant_id = p_tenant_id and sales_order_id = p_order_id and relation in ('RETURN', 'REPLACE', 'RESHIPMENT')) then
    for r in
      select distinct parent_sales_order_id as pid from groupbuy.sales_order_relations
       where tenant_id = p_tenant_id and sales_order_id = p_order_id and relation in ('RETURN', 'REPLACE', 'RESHIPMENT')
         and parent_sales_order_id is not null and parent_sales_order_id <> p_order_id
       order by 1
    loop
      perform groupbuy.sf_sync_order_membership(p_tenant_id, r.pid);
    end loop;
    return;
  end if;
  -- 鎖訂單（同一訂單的同步依序執行）
  select id, customer_id, state, total_paid, grand_total, created_at into o
    from groupbuy.sales_orders where id = p_order_id and tenant_id = p_tenant_id for no key update;
  if not found then
    return;
  end if;
  -- 可計入的 RP 明細：本單＋退貨／補寄子單（明細是從本單搬過去的），排除退貨完成／取消的明細
  for r in
    select oi.item_id, sum(oi.total)::integer as qty
      from groupbuy.order_items oi
      join groupbuy.items i on i.id = oi.item_id and i.tenant_id = oi.tenant_id and i.item_type = 'RP'
     where oi.tenant_id = p_tenant_id
       and (oi.sales_order_id = p_order_id
            or oi.sales_order_id in (select x.sales_order_id from groupbuy.sales_order_relations x
                                      where x.tenant_id = p_tenant_id and x.parent_sales_order_id = p_order_id and x.relation in ('RETURN', 'RESHIPMENT')))
       and oi.total > 0 and oi.state not in ('RETURNED', 'RETURNED_NOSALE', 'CANCELLED')
     group by oi.item_id
  loop
    v_items := v_items || jsonb_build_object(r.item_id::text, r.qty);
  end loop;
  -- 會員：依 id 升冪鎖（訂單會員 ∪ 生效紀錄的會員）
  perform 1 from groupbuy.customers c
    where c.tenant_id = p_tenant_id
      and c.id in (select o.customer_id
                   union
                   select x.customer_id from groupbuy.customer_royalty_grants x
                    where x.sales_order_id = p_order_id and x.tenant_id = p_tenant_id and x.revoked_at is null)
    order by c.id
      for no key update;
  v_keep := o.state not in ('DRAFT', 'CANCELED', 'DELETED', 'COMBINED', 'SPLITED', 'RETURNED');
  -- 加入：已完成，或已付清且確實有付款（0 元的暫時狀態——例如拆單新單搬明細時金額尚未重算——不算）；
  -- 截止日看根訂單（經 SPLIT／PARENT 關聯往上追的最早建立時間），舊單拆出來的新單也不會被補加入
  select min(a.created_at) into v_root
    from (with recursive up(id, depth) as (
            select p_order_id, 0
            union
            select y.parent_sales_order_id, up.depth + 1
              from up join groupbuy.sales_order_relations y
                on y.tenant_id = p_tenant_id and y.sales_order_id = up.id and y.relation in ('SPLIT', 'PARENT')
             where up.depth < 10 and y.parent_sales_order_id is not null)
          select s2.created_at from up join groupbuy.sales_orders s2 on s2.id = up.id and s2.tenant_id = p_tenant_id) a;
  v_grant := v_keep and o.customer_id is not null
             and (o.state = 'COMPLETE' or (coalesce(o.total_paid, 0) >= coalesce(o.grand_total, 0) and coalesce(o.total_paid, 0) > 0))
             and coalesce(v_root, o.created_at) >= timestamptz '2026-10-29 00:00:00+08';
  -- 1) 撤銷（後加入的先撤銷）
  for g in
    select * from groupbuy.customer_royalty_grants
     where sales_order_id = p_order_id and tenant_id = p_tenant_id and revoked_at is null
     order by id desc
  loop
    select coalesce(sum((v_items->>(x::text))::integer), 0) into v_qty from unnest(g.item_ids) x;
    v_reason := case
      when not v_keep then '訂單' || case o.state when 'CANCELED' then '取消' when 'DELETED' then '刪除' when 'RETURNED' then '退貨完成'
                                                   when 'COMBINED' then '已合併' when 'SPLITED' then '已拆單' else '狀態為 ' || o.state end
      when g.customer_id is distinct from o.customer_id then '訂單改綁其他會員'
      when v_qty <= 0 then '會員方案商品已退貨或移除'
      when o.state <> 'COMPLETE' and coalesce(o.total_paid, 0) < coalesce(o.grand_total, 0)
           and (coalesce(o.total_paid, 0) < g.paid_amount or g.paid_amount <= 0) then
        case when g.paid_amount <= 0 then '訂單未付款（加入時未實際付款）' else '退款後未付清' end
      else null end;
    if v_reason is not null then
      perform groupbuy.sf_royalty_grant_revoke(g.id, v_reason);
    end if;
  end loop;
  -- 2) 數量改變：減少隨時扣差額天數；回補到曾付清的數量以內（退貨申請途中的暫時減少）直接補；
  --    超過的增加要「已完成」或「付清且有新的付款」（已付超過上次記錄的最高已付）才補，
  --    避免改數量後、金額尚未重算的空檔就先補天數。之後記下最高已付（退款判斷）。
  for g in
    select * from groupbuy.customer_royalty_grants
     where sales_order_id = p_order_id and tenant_id = p_tenant_id and revoked_at is null
     order by id
  loop
    select coalesce(sum((v_items->>(x::text))::integer), 0) into v_qty from unnest(g.item_ids) x;
    if v_qty > 0 and (v_qty < g.qty
                      or (v_qty > g.qty and v_qty <= g.paid_qty)
                      or (v_qty > g.qty and v_grant and (o.state = 'COMPLETE' or coalesce(o.total_paid, 0) > g.paid_amount))) then
      perform groupbuy.sf_royalty_grant_adjust(g.id, v_qty, g.item_ids);
      update groupbuy.customer_royalty_grants set paid_qty = greatest(paid_qty, v_qty) where id = g.id;
    end if;
    if coalesce(o.total_paid, 0) > g.paid_amount then
      update groupbuy.customer_royalty_grants set paid_amount = o.total_paid, updated_at = now() where id = g.id;
    end if;
  end loop;
  -- 3) 新加入：尚未被生效紀錄涵蓋的 RP 商品，依目前綁定的方案分組
  if v_grant then
    select coalesce(array_agg(distinct x), '{}') into v_covered
      from groupbuy.customer_royalty_grants g2 cross join lateral unnest(g2.item_ids) x
     where g2.sales_order_id = p_order_id and g2.tenant_id = p_tenant_id and g2.revoked_at is null;
    for r in
      select irp.royalty_program_id as pid, array_agg(k.key::bigint order by k.key::bigint) as ids,
             sum((k.value #>> '{}')::integer)::integer as qty, max(coalesce(rp.duration_days, 0)) as days
        from jsonb_each(v_items) k
        join groupbuy.item_royalty_programs irp on irp.item_id = k.key::bigint and irp.tenant_id = p_tenant_id
        join groupbuy.royalty_programs rp on rp.id = irp.royalty_program_id and rp.tenant_id = p_tenant_id
       where not (k.key::bigint = any(v_covered))
       group by irp.royalty_program_id
       order by 1
    loop
      select * into g from groupbuy.customer_royalty_grants
       where sales_order_id = p_order_id and tenant_id = p_tenant_id and revoked_at is null and royalty_program_id = r.pid;
      if found then
        perform groupbuy.sf_royalty_grant_adjust(g.id, g.qty + r.qty, g.item_ids || r.ids);
        update groupbuy.customer_royalty_grants set paid_qty = greatest(paid_qty, qty) where id = g.id;
      else
        -- 參考時間：本單（同方案）之前加入過的、同交易內因搬移而撤銷的（合併）、拆單來源訂單的 → 取最早；都沒有＝現在
        select least(now(), min(x.ref_at)) into v_ref
          from groupbuy.customer_royalty_grants x
         where x.tenant_id = p_tenant_id and x.customer_id = o.customer_id and x.royalty_program_id = r.pid
           and (x.sales_order_id = p_order_id
                or (x.revoked_at = now() and x.item_ids && r.ids)
                or x.sales_order_id in (select y.parent_sales_order_id from groupbuy.sales_order_relations y
                                         where y.tenant_id = p_tenant_id and y.sales_order_id = p_order_id and y.relation in ('SPLIT', 'PARENT')));
        perform groupbuy.sf_royalty_grant_apply(p_tenant_id, o.customer_id, p_order_id, r.pid, r.ids, r.qty, r.days,
                                                coalesce(o.total_paid, 0), coalesce(v_ref, now()));
      end if;
    end loop;
  end if;
end
$$;

