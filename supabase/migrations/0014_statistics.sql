-- 重算租戶的每日/月統計表（排程或「重新整理」按鈕呼叫：select groupbuy.refresh_tenant_statistics(:tenant_id)）
create or replace function groupbuy.refresh_tenant_statistics(p_tenant_id bigint) returns void
language plpgsql security definer set search_path = groupbuy, pg_temp as $$
declare gid bigint;
begin
  delete from groupbuy.group_buy_daily_statistics where tenant_id = p_tenant_id;
  insert into groupbuy.group_buy_daily_statistics
    (tenant_id, group_buy_id, date_statistics, title, short_url, amount_sales, count_sales,
     amount_sales_paid, count_sales_paid, amount_sales_unpaid, count_sales_unpaid)
  select o.tenant_id, o.group_buy_id, (o.created_at at time zone 'Asia/Taipei')::date, g.title, g.short_url,
         sum(o.grand_total), count(*),
         coalesce(sum(o.grand_total) filter (where o.total_paid > 0), 0), count(*) filter (where o.total_paid > 0),
         coalesce(sum(o.grand_total) filter (where o.total_paid = 0), 0), count(*) filter (where o.total_paid = 0)
    from groupbuy.sales_orders o
    join groupbuy.group_buys g on g.id = o.group_buy_id
   where o.tenant_id = p_tenant_id and groupbuy.is_valid_order_state(o.state)
   group by o.tenant_id, o.group_buy_id, (o.created_at at time zone 'Asia/Taipei')::date, g.title, g.short_url;

  delete from groupbuy.item_daily_statistics where tenant_id = p_tenant_id;
  insert into groupbuy.item_daily_statistics
    (tenant_id, group_buy_id, item_id, date_statistics, title, uid, amount_sales, count_sales)
  select o.tenant_id, o.group_buy_id, oi.item_id, (o.created_at at time zone 'Asia/Taipei')::date,
         max(oi.title), max(oi.uid), sum(oi.amount), sum(oi.total)
    from groupbuy.order_items oi
    join groupbuy.sales_orders o on o.id = oi.sales_order_id
   where o.tenant_id = p_tenant_id and oi.item_id is not null and groupbuy.is_valid_order_state(o.state)
   group by o.tenant_id, o.group_buy_id, oi.item_id, (o.created_at at time zone 'Asia/Taipei')::date;

  delete from groupbuy.group_buy_erp_monthly_statistics where tenant_id = p_tenant_id;
  insert into groupbuy.group_buy_erp_monthly_statistics
    (tenant_id, group_buy_id, date_statistics, title, short_url, amount_total, count_total)
  select o.tenant_id, o.group_buy_id, date_trunc('month', o.created_at at time zone 'Asia/Taipei')::date, g.title, g.short_url,
         sum(o.grand_total), count(*)
    from groupbuy.sales_orders o
    join groupbuy.group_buys g on g.id = o.group_buy_id
   where o.tenant_id = p_tenant_id and groupbuy.is_valid_order_state(o.state)
   group by o.tenant_id, o.group_buy_id, date_trunc('month', o.created_at at time zone 'Asia/Taipei')::date, g.title, g.short_url;

  delete from groupbuy.sales_order_monthly_statistics where tenant_id = p_tenant_id;
  insert into groupbuy.sales_order_monthly_statistics
    (tenant_id, month, customer_id, name, email, telephone, amount_total, amount_max, count_order_valid)
  select o.tenant_id, date_trunc('month', o.created_at at time zone 'Asia/Taipei')::date, max(o.customer_id),
         max(o.customer_firstname), lower(coalesce(o.customer_email, '')), coalesce(o.customer_telephone, ''),
         sum(o.grand_total), max(o.grand_total), count(*)
    from groupbuy.sales_orders o
   where o.tenant_id = p_tenant_id and groupbuy.is_valid_order_state(o.state)
   group by o.tenant_id, date_trunc('month', o.created_at at time zone 'Asia/Taipei')::date,
            lower(coalesce(o.customer_email, '')), coalesce(o.customer_telephone, '');

  for gid in select id from groupbuy.group_buys where tenant_id = p_tenant_id loop
    perform groupbuy.refresh_group_buy_statistics(gid);
  end loop;
end $$;

