-- 團購統計重算（groupBuyStatistics.* 與首單時間）
create or replace function groupbuy.refresh_group_buy_statistics(p_group_buy_id bigint) returns void
language plpgsql security definer set search_path = groupbuy, pg_temp as $$
declare
  v_share numeric;
  v_stats jsonb;
  v_first timestamptz;
begin
  select blogger_share into v_share from groupbuy.group_buys where id = p_group_buy_id;
  if not found then return; end if;
  with o as (
    select * from groupbuy.sales_orders
     where group_buy_id = p_group_buy_id and groupbuy.is_valid_order_state(state)
  ), agg as (
    select count(*) as orders,
           count(*) filter (where created_at >= (date_trunc('month', now() at time zone 'Asia/Taipei') at time zone 'Asia/Taipei')) as month_orders,
           count(*) filter (where state in ('NEW','PROCESSING') and total_paid = 0
                              and status in ('ORDER_EMAIL_SENT','SEND_ORDER_EMAIL','ORDER_EMAIL_FAILED')) as unprocessed,
           count(*) filter (where total_paid > 0) as paid_orders,
           count(*) filter (where state in ('NEW','PROCESSING') and date_shipped is null and shipping_type <> 'NOD'
                              and status not in ('SHIPPED','SHIPPING_EMAIL_SENT','SHIPPING_EMAIL_FAILED','PREPARE_SHIPPING','PICKING')) as unshipped,
           count(*) filter (where state in ('NEW','PROCESSING') and date_shipped is null and contain_back_orders) as unshipped_back,
           count(*) filter (where state in ('NEW','PROCESSING') and total_paid = 0 and date_payment_due < now()) as payment_due,
           count(*) filter (where status = 'PAID_AMOUNT_MISMATCHED') as payment_incorrect,
           count(*) filter (where status = 'EINVOICE_FAILED') as einvoice_failed,
           count(*) filter (where status = 'CVS_PICKUP_DATE_DUED') as cvs_dued,
           coalesce(sum(grand_total), 0) as revenue,
           coalesce(sum(grand_total - shipping_amount), 0) as revenue_wo_ship,
           coalesce(sum(total_paid), 0) as paid_total,
           coalesce(sum(case when total_paid > 0 then total_paid - shipping_amount else 0 end), 0) as paid_wo_ship,
           coalesce(sum(case when billing_installment <> 'NONE' then total_paid else 0 end), 0) as paid_installment,
           coalesce(sum(internal_shipping_amount), 0) as internal_ship,
           count(distinct nullif(shipping_tag, '')) as shipping_tags,
           min(created_at) as first_order
      from o
  ), comm as (
    select coalesce(sum(oi.price * oi.total * oi.commission_rate / 100 + oi.commission_dollar * oi.total), 0) as commissions
      from groupbuy.order_items oi join o on o.id = oi.sales_order_id
  ), its as (
    select count(*) filter (where i.offline or gbis.option_offline) as offline_items,
           count(*) filter (where not i.offline and not gbis.option_offline
                              and i.stock_available <= 0 and i.stock_back_order_available <= 0) as oos_items
      from groupbuy.group_buy_item_sets gbis
      join groupbuy.items i on i.item_set_id = gbis.item_set_id
     where gbis.group_buy_id = p_group_buy_id
  )
  select jsonb_build_object(
           'orders', agg.orders, 'monthOrders', agg.month_orders, 'unprocessedOrders', agg.unprocessed,
           'paidOrders', agg.paid_orders, 'unshippedOrders', agg.unshipped, 'unshippedBackOrders', agg.unshipped_back,
           'paymentDueOrders', agg.payment_due, 'paymentIncorrectOrders', agg.payment_incorrect,
           'einvoiceFailedOrders', agg.einvoice_failed, 'cvsDateDuedOrders', agg.cvs_dued,
           'revenue', agg.revenue, 'revenueWithoutShipping', agg.revenue_wo_ship, 'paidTotal', agg.paid_total,
           'paidTotalWithoutShipping', agg.paid_wo_ship, 'paidTotalInstallment', agg.paid_installment,
           'bloggerShareTotal', round(agg.revenue_wo_ship * coalesce(v_share, 0) / 100, 2),
           'internalShippingAmount', agg.internal_ship, 'commissionsTotal', round(comm.commissions, 2),
           'shippingTags', agg.shipping_tags, 'offlineItems', its.offline_items, 'outOfStockItems', its.oos_items,
           'countUnshippedOrders', agg.unshipped),
         agg.first_order
    into v_stats, v_first
    from agg, comm, its;
  update groupbuy.group_buys
     set group_buy_statistics = v_stats, date_first_order = v_first
   where id = p_group_buy_id
     and (group_buy_statistics is distinct from v_stats or date_first_order is distinct from v_first);
end $$;

-- group_buys：只有統計欄位變動時不更新 updated_at（避免干擾 dateModified 樂觀鎖）
create or replace function groupbuy.touch_group_buys_updated_at() returns trigger
language plpgsql set search_path = groupbuy, pg_temp as $$
begin
  if (to_jsonb(new) - 'group_buy_statistics' - 'date_first_order' - 'updated_at')
     is distinct from (to_jsonb(old) - 'group_buy_statistics' - 'date_first_order' - 'updated_at') then
    new.updated_at := now();
  end if;
  return new;
end $$;
drop trigger if exists group_buys_touch on groupbuy.group_buys;
create trigger group_buys_touch before update on groupbuy.group_buys
  for each row execute function groupbuy.touch_group_buys_updated_at();

-- 訂單異動 → 重算所屬團購統計（statement-level，批次寫入只算一次）
create or replace function groupbuy.sales_orders_refresh_stats() returns trigger
language plpgsql security definer set search_path = groupbuy, pg_temp as $$
declare gid bigint;
begin
  if tg_op = 'INSERT' then
    for gid in select distinct group_buy_id from new_rows where group_buy_id is not null loop
      perform groupbuy.refresh_group_buy_statistics(gid);
    end loop;
  elsif tg_op = 'UPDATE' then
    for gid in select group_buy_id from new_rows where group_buy_id is not null
               union select group_buy_id from old_rows where group_buy_id is not null loop
      perform groupbuy.refresh_group_buy_statistics(gid);
    end loop;
  else
    for gid in select distinct group_buy_id from old_rows where group_buy_id is not null loop
      perform groupbuy.refresh_group_buy_statistics(gid);
    end loop;
  end if;
  return null;
end $$;
drop trigger if exists sales_orders_stats_ins on groupbuy.sales_orders;
drop trigger if exists sales_orders_stats_upd on groupbuy.sales_orders;
drop trigger if exists sales_orders_stats_del on groupbuy.sales_orders;
create trigger sales_orders_stats_ins after insert on groupbuy.sales_orders
  referencing new table as new_rows for each statement execute function groupbuy.sales_orders_refresh_stats();
create trigger sales_orders_stats_upd after update on groupbuy.sales_orders
  referencing old table as old_rows new table as new_rows for each statement execute function groupbuy.sales_orders_refresh_stats();
create trigger sales_orders_stats_del after delete on groupbuy.sales_orders
  referencing old table as old_rows for each statement execute function groupbuy.sales_orders_refresh_stats();

-- 訂單商品異動 → 維護 sales_orders.contain_back_orders（並連帶觸發統計）
create or replace function groupbuy.order_items_sync_order() returns trigger
language plpgsql security definer set search_path = groupbuy, pg_temp as $$
begin
  if tg_op = 'DELETE' then
    update groupbuy.sales_orders o
       set contain_back_orders = exists (select 1 from groupbuy.order_items oi where oi.sales_order_id = o.id and oi.back_order)
     where o.id in (select distinct sales_order_id from old_rows)
       and o.contain_back_orders is distinct from exists (select 1 from groupbuy.order_items oi where oi.sales_order_id = o.id and oi.back_order);
  else
    update groupbuy.sales_orders o
       set contain_back_orders = exists (select 1 from groupbuy.order_items oi where oi.sales_order_id = o.id and oi.back_order)
     where o.id in (select distinct sales_order_id from new_rows)
       and o.contain_back_orders is distinct from exists (select 1 from groupbuy.order_items oi where oi.sales_order_id = o.id and oi.back_order);
  end if;
  return null;
end $$;
drop trigger if exists order_items_sync_ins on groupbuy.order_items;
drop trigger if exists order_items_sync_upd on groupbuy.order_items;
drop trigger if exists order_items_sync_del on groupbuy.order_items;
create trigger order_items_sync_ins after insert on groupbuy.order_items
  referencing new table as new_rows for each statement execute function groupbuy.order_items_sync_order();
create trigger order_items_sync_upd after update on groupbuy.order_items
  referencing old table as old_rows new table as new_rows for each statement execute function groupbuy.order_items_sync_order();
create trigger order_items_sync_del after delete on groupbuy.order_items
  referencing old table as old_rows for each statement execute function groupbuy.order_items_sync_order();

