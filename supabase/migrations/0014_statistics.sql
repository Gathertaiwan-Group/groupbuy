-- 商品銷售分析檢視（/ajax/SalesAnalysis/queryOrderItemAnalysis 的資料來源）
create or replace view groupbuy.order_item_analysis_v as
select oi.id as order_item_id,
       oi.tenant_id,
       to_char(o.created_at at time zone 'Asia/Taipei', 'YYYY-MM') as month,
       o.group_buy_id,
       g.title as group_buy_title,
       oi.item_id,
       oi.title,
       oi.uid,
       oi.state,
       oi.total,
       oi.price,
       oi.amount,
       case when oi.total > 0 then round(oi.amount / oi.total, 2) else 0 end as unit_price,
       (o.shipping_amount > 0) as has_shipping_amount,
       o.id as sales_order_id,
       o.created_at as date_created,
       o.date_paid
  from groupbuy.order_items oi
  join groupbuy.sales_orders o on o.id = oi.sales_order_id
  left join groupbuy.group_buys g on g.id = o.group_buy_id
 where o.state not in ('DRAFT','CANCELED','DELETED','COMBINED','SPLITED');


