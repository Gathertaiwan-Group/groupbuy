-- 6006 storefront／marketing：訂單作廢／取消時退回優惠名額（fix4）。只動 groupbuy schema。
-- 背景：前台下單（sf_place_order，6001）與 POS 結帳（pos_checkout，6003）在同一交易內把
--   折扣碼 coupon_codes.used_count、團購優惠卷 group_buy_coupons.coupon_used_total、優惠條件 sales_rules.used_quota 各 +1，
--   但 POS 作廢（6005 pos_void_order）與後台「取消訂單」都不會扣回 → 名額被作廢單永久占用。
-- 作法：
--   1) 名額帳本 sales_order_marketing_usages：結帳當下「實際 +1 了哪些名額」逐項記錄（kind＋ref_id＋qty），released_at 標記是否已退回。
--      sales_order_coupons／sales_order_sales_rules 會被後台重新計算或 POS 草稿改寫，不能當作「用掉了什麼」的依據，所以另立帳本。
--      本 migration 之前成立的訂單沒有帳本 → 不退（示範資料的計數本來就和訂單對不上，不能用明細回推）。
--   2) sf_place_order／pos_checkout 改為薄包裝：原函式更名為 *_core（內容不變），包裝在同一交易內呼叫 core 後寫帳本。
--      🔴 之後要改下單／結帳邏輯，請 create or replace groupbuy.sf_place_order_core／pos_checkout_core，不要覆蓋包裝函式。
--   3) 觸發器（sales_orders.state 變更）：
--      進入 CANCELED／DELETED（從其他階段）→ marketing_release_order_usage：未退回的帳本列逐項扣回（不低於 0），標記 released_at。
--      從 CANCELED／DELETED 改回其他階段（後台「還原已取消訂單」）→ marketing_reclaim_order_usage：已退回的列重新占用並清除標記
--      （還原的是原本就屬於這張單的名額，不再檢查上限）。
--      以 released_at 判斷 → 重複作廢／取消、取消後再刪除都不會重複退；POS 作廢經 orders_admin_update 改階段，同樣觸發。

create table if not exists groupbuy.sales_order_marketing_usages (
  id bigint generated by default as identity primary key,
  tenant_id bigint not null references groupbuy.tenants(id) on delete cascade,
  sales_order_id bigint not null references groupbuy.sales_orders(id) on delete cascade,
  kind text not null check (kind in ('COUPON_CODE', 'GROUP_BUY_COUPON', 'SALES_RULE')),
  ref_id bigint not null,
  qty integer not null check (qty > 0),
  released_at timestamptz,
  created_at timestamptz not null default now(),
  unique (sales_order_id, kind, ref_id)
);
create index if not exists somu_tenant_idx on groupbuy.sales_order_marketing_usages(tenant_id);
alter table groupbuy.sales_order_marketing_usages enable row level security;
revoke all on groupbuy.sales_order_marketing_usages from anon, authenticated;
grant all on groupbuy.sales_order_marketing_usages to service_role;
grant usage, select on all sequences in schema groupbuy to service_role;
revoke all on all sequences in schema groupbuy from anon, authenticated;

-- 依下單／結帳 payload 的 couponCodeIds／groupBuyCouponIds／salesRuleIds（與 core 函式 +1 的依據完全相同）寫帳本
create or replace function groupbuy.marketing_record_order_usage(p_tenant_id bigint, p_sales_order_id bigint, p jsonb)
returns void
language plpgsql
set search_path = groupbuy, pg_temp
as $$
begin
  if p_tenant_id is null or p_sales_order_id is null then
    return;
  end if;
  insert into groupbuy.sales_order_marketing_usages (tenant_id, sales_order_id, kind, ref_id, qty)
  select p_tenant_id, p_sales_order_id, s.kind, s.ref_id, count(*)::integer
    from (
      select 'COUPON_CODE'::text as kind, nullif(x #>> '{}', '')::bigint as ref_id
        from jsonb_array_elements(case when jsonb_typeof(p->'couponCodeIds') = 'array' then p->'couponCodeIds' else '[]'::jsonb end) x
      union all
      select 'GROUP_BUY_COUPON', nullif(x #>> '{}', '')::bigint
        from jsonb_array_elements(case when jsonb_typeof(p->'groupBuyCouponIds') = 'array' then p->'groupBuyCouponIds' else '[]'::jsonb end) x
      union all
      select 'SALES_RULE', nullif(x #>> '{}', '')::bigint
        from jsonb_array_elements(case when jsonb_typeof(p->'salesRuleIds') = 'array' then p->'salesRuleIds' else '[]'::jsonb end) x
    ) s
   where s.ref_id is not null
   group by s.kind, s.ref_id
  on conflict (sales_order_id, kind, ref_id)
  do update set qty = groupbuy.sales_order_marketing_usages.qty + excluded.qty;
end
$$;

-- 退回（冪等）：只處理尚未退回的帳本列；計數不低於 0
create or replace function groupbuy.marketing_release_order_usage(p_tenant_id bigint, p_sales_order_id bigint)
returns jsonb
language plpgsql
set search_path = groupbuy, pg_temp
as $$
declare
  r record;
  v_out jsonb := '[]'::jsonb;
begin
  for r in
    select u.id, u.kind, u.ref_id, u.qty
      from groupbuy.sales_order_marketing_usages u
     where u.sales_order_id = p_sales_order_id and u.tenant_id = p_tenant_id and u.released_at is null
     order by u.kind, u.ref_id
       for update
  loop
    if r.kind = 'COUPON_CODE' then
      update groupbuy.coupon_codes set used_count = greatest(used_count - r.qty, 0)
       where id = r.ref_id and tenant_id = p_tenant_id;
    elsif r.kind = 'GROUP_BUY_COUPON' then
      update groupbuy.group_buy_coupons set coupon_used_total = greatest(coupon_used_total - r.qty, 0)
       where id = r.ref_id and tenant_id = p_tenant_id;
    elsif r.kind = 'SALES_RULE' then
      update groupbuy.sales_rules set used_quota = greatest(used_quota - r.qty, 0)
       where id = r.ref_id and tenant_id = p_tenant_id;
    end if;
    update groupbuy.sales_order_marketing_usages set released_at = now() where id = r.id;
    v_out := v_out || jsonb_build_array(jsonb_build_object('kind', r.kind, 'refId', r.ref_id, 'qty', r.qty));
  end loop;
  return v_out;
end
$$;

-- 重新占用（還原已取消訂單；冪等）：只處理已退回的帳本列
create or replace function groupbuy.marketing_reclaim_order_usage(p_tenant_id bigint, p_sales_order_id bigint)
returns jsonb
language plpgsql
set search_path = groupbuy, pg_temp
as $$
declare
  r record;
  v_out jsonb := '[]'::jsonb;
begin
  for r in
    select u.id, u.kind, u.ref_id, u.qty
      from groupbuy.sales_order_marketing_usages u
     where u.sales_order_id = p_sales_order_id and u.tenant_id = p_tenant_id and u.released_at is not null
     order by u.kind, u.ref_id
       for update
  loop
    if r.kind = 'COUPON_CODE' then
      update groupbuy.coupon_codes set used_count = used_count + r.qty, date_used = coalesce(date_used, now())
       where id = r.ref_id and tenant_id = p_tenant_id;
    elsif r.kind = 'GROUP_BUY_COUPON' then
      update groupbuy.group_buy_coupons set coupon_used_total = coupon_used_total + r.qty
       where id = r.ref_id and tenant_id = p_tenant_id;
    elsif r.kind = 'SALES_RULE' then
      update groupbuy.sales_rules set used_quota = used_quota + r.qty
       where id = r.ref_id and tenant_id = p_tenant_id;
    end if;
    update groupbuy.sales_order_marketing_usages set released_at = null where id = r.id;
    v_out := v_out || jsonb_build_array(jsonb_build_object('kind', r.kind, 'refId', r.ref_id, 'qty', r.qty));
  end loop;
  return v_out;
end
$$;

create or replace function groupbuy.trg_sales_orders_marketing_usage()
returns trigger
language plpgsql
set search_path = groupbuy, pg_temp
as $$
declare
  v_old_off boolean := coalesce(old.state in ('CANCELED', 'DELETED'), false);
  v_new_off boolean := coalesce(new.state in ('CANCELED', 'DELETED'), false);
begin
  if v_new_off and not v_old_off then
    perform groupbuy.marketing_release_order_usage(new.tenant_id, new.id);
  elsif v_old_off and not v_new_off then
    perform groupbuy.marketing_reclaim_order_usage(new.tenant_id, new.id);
  end if;
  return new;
end
$$;

drop trigger if exists sales_orders_marketing_usage on groupbuy.sales_orders;
create trigger sales_orders_marketing_usage
  after update of state on groupbuy.sales_orders
  for each row
  when (old.state is distinct from new.state)
  execute function groupbuy.trg_sales_orders_marketing_usage();

