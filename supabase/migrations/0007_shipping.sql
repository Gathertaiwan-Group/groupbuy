-- 0007 運費與物流設定：運費規則 FlatRateShipping（租戶層）、團購×運費規則、品項運費、貨運標籤 ShippingTag、自取通路與門市

create table if not exists groupbuy.flat_rate_shippings (
  id bigint generated by default as identity primary key,           -- flatRateShippingId
  tenant_id bigint not null references groupbuy.tenants(id) on delete cascade,
  shipping_type text not null default 'NORMAL' check (shipping_type in ('NORMAL','PICKUP','CVS','INTL','NOD','HK_SF')), -- 新增後不可改
  category text not null default 'PRICE' check (category in ('PRICE_TAG','PIECE_TAG','WEIGHT','PER_PIECE','MIX','PRICE','PIECE','STANDARD_FREE')),
  title text not null default '',
  seq integer not null default 0,
  x numeric(14,2) not null default 0,                                -- 滿足條件 x
  y numeric(14,2) not null default 0,                                -- 基本運費 y
  z numeric(14,2) not null default 0,                                -- 滿足條件後基本運費 z
  pay_on_delivery_fee numeric(14,2) not null default 0,              -- 貨到付款
  island_fee numeric(14,2) not null default 0,                       -- 外島費用(舊)
  island_fee_x numeric(14,2),
  island_fee_y numeric(14,2),
  island_fee_z numeric(14,2),
  island_shipping_rate_type text not null default 'REPLACE_BASE_RATE' check (island_shipping_rate_type in ('REPLACE_BASE_RATE','TOP_ON_BASE_RATE')),
  oversea_fee numeric(14,2) not null default 0,                      -- 國外運費
  extended_area_fee numeric(14,2) not null default 0,                -- 偏遠地區費用
  extended_areas text[] not null default '{}'::text[],               -- 偏遠地區郵遞區號（extendedAreas[]；extendedArea 為逗點字串）
  islands text[] not null default '{}'::text[],                      -- 配送外島郵遞區號（islands[]；'0'=全選）
  flat_rate_shipping_tag text,                                       -- 運費標籤（多行「標籤#基本運費#滿足後運費#E|R#件數或金額」）
  subset_apply_full_amount boolean not null default false,
  coupon_x boolean not null default false,                           -- 滿足條件x需搭配折扣碼
  payment_methods text[] not null default '{}'::text[]
    check (payment_methods <@ array['BANK_ACCOUNT','VIRTUAL_BANK','ALLPAY_CREDITCARD','PICKUP','PAY_ON_DELIVERY','CVS','CVS_PICKUP','PERIOD','CUSTOM','EMPLOYEE_PURCHASE','LINEPAY','POINT','EASYCARD','TAIWANPAY','UNIONPAY']::text[]),
  island_payment_methods text[] not null default '{}'::text[]
    check (island_payment_methods <@ array['BANK_ACCOUNT','VIRTUAL_BANK','ALLPAY_CREDITCARD','PICKUP','PAY_ON_DELIVERY','CVS','CVS_PICKUP','PERIOD','CUSTOM','EMPLOYEE_PURCHASE','LINEPAY','POINT','EASYCARD','TAIWANPAY','UNIONPAY']::text[]),
  flat_rate_shipping_settings jsonb not null default '{
    "cvsType": "", "tenantId": null,
    "main": {"tieredPrices": [], "tieredPricesString": ""},
    "island": {"tieredPrices": [], "tieredPricesString": ""},
    "oversea": {"tieredPrices": [], "tieredPricesString": ""},
    "payOnDeliveryFee": {"tieredPrices": [], "tieredPricesString": ""},
    "freeShippingAsInternalShipping": false, "restrictedShippingTag": "", "shippingTag": "",
    "freeShippingLabel": "免運", "shippingCountry": [], "shippingCountryExcluded": [],
    "shippingAreas": [], "extendedAreas": [], "shippingType": "NOT_USED",
    "subsetApplyHighestAmount": false, "subsetApplyLowestAmount": false, "descr": "",
    "weightLimit": "", "amountLimit": "", "orderStockType": "ANY"
  }'::jsonb,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create index if not exists flat_rate_shippings_tenant_idx on groupbuy.flat_rate_shippings(tenant_id, seq);

-- 團購 × 運費規則（/ajax/GroupBuyFlatRateShipping/list；團購 Editor groupBuyFlatRateShippings[].flatRateShippingId）
create table if not exists groupbuy.group_buy_flat_rate_shippings (
  id bigint generated by default as identity primary key,           -- groupBuyFlatRateShippingId
  tenant_id bigint not null references groupbuy.tenants(id) on delete cascade,
  group_buy_id bigint not null references groupbuy.group_buys(id) on delete cascade,
  flat_rate_shipping_id bigint not null references groupbuy.flat_rate_shippings(id) on delete cascade,
  seq integer not null default 0,
  created_at timestamptz not null default now(),
  unique (group_buy_id, flat_rate_shipping_id)
);
create index if not exists gbfrs_tenant_idx on groupbuy.group_buy_flat_rate_shippings(tenant_id);
create index if not exists gbfrs_frs_idx on groupbuy.group_buy_flat_rate_shippings(flat_rate_shipping_id);

-- 品項運費（GroupBuyItemSetFlatRateShipping；團購品項 Editor groupBuyItemSetFlatRateShipping.flatRateShippingId）
create table if not exists groupbuy.group_buy_item_set_flat_rate_shippings (
  id bigint generated by default as identity primary key,           -- groupBuyItemSetFlatRateShippingId
  tenant_id bigint not null references groupbuy.tenants(id) on delete cascade,
  group_buy_id bigint not null references groupbuy.group_buys(id) on delete cascade,
  group_buy_item_set_id bigint not null references groupbuy.group_buy_item_sets(id) on delete cascade,
  flat_rate_shipping_id bigint not null references groupbuy.flat_rate_shippings(id) on delete cascade,
  created_at timestamptz not null default now(),
  unique (group_buy_item_set_id)
);
create index if not exists gbisfrs_tenant_idx on groupbuy.group_buy_item_set_flat_rate_shippings(tenant_id);
create index if not exists gbisfrs_group_buy_idx on groupbuy.group_buy_item_set_flat_rate_shippings(group_buy_id);

-- 貨運標籤（ShippingTag：物流商格式、匯入貨運表標頭對應、自定義匯出格式）
create table if not exists groupbuy.shipping_tags (
  id bigint generated by default as identity primary key,           -- shippingTagId
  tenant_id bigint not null references groupbuy.tenants(id) on delete cascade,
  title text not null default '',
  tag text not null default '',                                      -- 標籤（大型/物流/宅配/7-11超商取貨…；團購/商品/訂單的 shippingTag 值）
  shipping_provider text,                                            -- 貨運格式（HCT_STANDARD…共 60 種，見 enum ShippingTag.shippingProvider）
  sales_order_uuid text,                                             -- 匯入貨運表-訂單編號標頭名稱
  sales_order_shipping_receipt_number text,                          -- 匯入貨運表-貨運編號標頭名稱
  shipping_export_format text,                                       -- 自定義匯出格式
  shipping_tag_settings jsonb not null default '{"largeItem": false, "spacePerBox": ""}'::jsonb,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create index if not exists shipping_tags_tenant_idx on groupbuy.shipping_tags(tenant_id);

-- 自取通路（PickupStore setting）與門市
create table if not exists groupbuy.pickup_store_settings (
  id bigint generated by default as identity primary key,           -- pickupStoreSettingId
  tenant_id bigint not null references groupbuy.tenants(id) on delete cascade,
  title text not null default '',                                    -- 自取通路名稱
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create index if not exists pickup_store_settings_tenant_idx on groupbuy.pickup_store_settings(tenant_id);

create table if not exists groupbuy.pickup_stores (
  id bigint generated by default as identity primary key,           -- pickupStoreId
  tenant_id bigint not null references groupbuy.tenants(id) on delete cascade,
  pickup_store_setting_id bigint not null references groupbuy.pickup_store_settings(id) on delete cascade,
  store_code text,
  store_name text not null default '',
  address text not null default '',
  postal_code text,
  longitude numeric(10,6),
  latitude numeric(10,6),
  seq integer not null default 0,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create index if not exists pickup_stores_setting_idx on groupbuy.pickup_stores(pickup_store_setting_id, seq);
create index if not exists pickup_stores_tenant_idx on groupbuy.pickup_stores(tenant_id);

