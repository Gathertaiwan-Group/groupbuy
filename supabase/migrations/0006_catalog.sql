-- 0006 商品目錄：品項本體 ItemSet、團購品項 GroupBuyItemSet（團購×品項，可共用庫存）、商品 Item、組合商品 ItemBundleV2、
--      商品系統標籤 / 銷售標籤 / 關鍵字標籤、商品會員價、虛擬商品序號

-- 品項本體（ItemSet：title/tab1-3/descr/圖片/輪播；可被多個團購共用＝「複製(共用庫存)」）
create table if not exists groupbuy.item_sets (
  id bigint generated by default as identity primary key,           -- itemSetId
  tenant_id bigint not null references groupbuy.tenants(id) on delete cascade,
  uuid text not null default replace(gen_random_uuid()::text, '-', ''),
  title text not null default '',                                    -- 品項名稱
  cate_tag text,                                                     -- 分類標籤(#區隔)
  tab1_title text default '產品介紹',
  tab1_descr text,
  tab2_title text,
  tab2_descr text,
  tab3_title text,
  tab3_descr text,
  descr text,                                                        -- 短敘述(用於樣式2,3)
  image text,
  image_url text,                                                    -- 圖片連結
  image2 text,                                                       -- 分頁1圖片
  carousel1 text, carousel2 text, carousel3 text, carousel4 text,
  carousel1_url text, carousel2_url text, carousel3_url text, carousel4_url text,
  item_set_settings jsonb not null default '{
    "title": "", "subtitle": "", "hideTitle": false, "shortName": "", "galleryMode": "",
    "itemStyle": "STYLE1", "packageMainItemSetId": null, "googleFormUrl": "", "url301": ""
  }'::jsonb,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create index if not exists item_sets_tenant_idx on groupbuy.item_sets(tenant_id);
create unique index if not exists item_sets_uuid_key on groupbuy.item_sets(uuid);

-- 團購品項（GroupBuyItemSet：/ajax/GroupBuyItemSet/list；排序、樣式、上下架）
create table if not exists groupbuy.group_buy_item_sets (
  id bigint generated by default as identity primary key,           -- groupBuyItemSetId
  tenant_id bigint not null references groupbuy.tenants(id) on delete cascade,
  group_buy_id bigint not null references groupbuy.group_buys(id) on delete cascade,
  item_set_id bigint not null references groupbuy.item_sets(id) on delete cascade,
  seq integer not null default 0,
  style text not null default 'STYLE1' check (style in ('STYLE1','STYLE2','STYLE32','STYLE31','STYLE3','STYLE6','STYLE5','STYLE4','STYLE7','STYLE8','DESCR','STYLE9','TRAVEL_HOTEL','TRAVEL_AIR_TICKET_DEPARTURE','TRAVEL_AIR_TICKET_RETURN','TRAVEL_ADDITIONAL')),
  item_set_top_style text not null default 'STYLE1' check (item_set_top_style in ('STYLE1','STYLE2','STYLE3','STYLE4')),
  combinable boolean not null default false,
  css text,
  css_title text,
  css_normal_select text,
  css_backorder_select text,
  option_offline boolean not null default false,                     -- 下架
  option_offline_when_sold_out boolean not null default false,
  ready_for_sale boolean not null default true,                      -- 銷售中
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (group_buy_id, item_set_id)
);
create index if not exists group_buy_item_sets_tenant_idx on groupbuy.group_buy_item_sets(tenant_id);
create index if not exists group_buy_item_sets_group_buy_idx on groupbuy.group_buy_item_sets(group_buy_id, seq);
create index if not exists group_buy_item_sets_item_set_idx on groupbuy.group_buy_item_sets(item_set_id);

-- 商品（Item：/ajax/Item/list；價格/庫存/規格/類型）
create table if not exists groupbuy.items (
  id bigint generated by default as identity primary key,           -- itemId
  tenant_id bigint not null references groupbuy.tenants(id) on delete cascade,
  item_set_id bigint not null references groupbuy.item_sets(id) on delete cascade,
  parent_item_id bigint references groupbuy.items(id) on delete set null, -- 群組主商品（共用主庫存 / 規格主商品）
  share_stock boolean not null default false,                        -- 與主商品共用庫存
  seq integer not null default 0,
  uid text,                                                          -- 商品代碼
  upc text,                                                          -- 國際條碼
  title text not null default '',                                    -- 名稱(訂單顯示)
  short_name_display text,                                           -- 短名稱(表單顯示)
  short_name text,                                                   -- 短名稱(出貨用)
  tag text,                                                          -- 名稱標籤(#區隔)
  cate_tag text,                                                     -- 分類標籤(#區隔)
  retail_price numeric(14,2),                                        -- 原價
  price numeric(14,2) not null default 0,                            -- 團購價
  cprice numeric(14,2) not null default 0,                           -- 成本
  stock integer not null default 0,                                  -- 原始現貨庫存
  stock_available integer not null default 0,                        -- 可售現貨數量
  stock_cache integer not null default 0,                            -- 保留現貨數量
  max_order_quota integer not null default 10,                       -- 最大下單量（0=前台顯示缺貨）
  stock_back_order integer not null default 0,                       -- 原始預購庫存
  stock_back_order_available integer not null default 0,             -- 可售預購數量
  offline boolean not null default false,                            -- 下架
  option_offline_when_sold_out boolean not null default false,
  attribute_note boolean not null default false,                     -- 使用備註
  attribute_note_default text,                                       -- 說明備註內容
  exclude_shipping_rule boolean not null default false,              -- 不列入運費計算
  shipping_price numeric(14,2),                                      -- 單件商品運費(依購買件數累加)
  internal_shipping_price numeric(14,2),                             -- 單件商品運費(免運成本)
  flat_rate_shipping_tag text not null default '',                   -- 運費標籤
  shipping_tag text not null default '',                             -- 貨運標籤
  shipping_provider text,                                            -- 商品指定貨運格式（如 KTJ_STANDARD）
  commission_rate numeric(8,2) not null default 0,                   -- 分潤(%)
  commission_dollar numeric(14,2) not null default 0,                -- 分潤(元/個)
  item_type text not null default 'NORMAL' check (item_type in ('NORMAL','GIFT','VIRTUAL','SEQ','SHIPPING','COD','DIFF','DISCOUNT','COUPON','POINT','SPEC_MAIN','SPEC_SUB','ROOM','SUBSCRIPTION','ZERO','RP','LOYALTY_CARD','BUNDLE_V2')),
  virtual_item_code_prefix text,
  sys_tags text[] not null default '{}'::text[]
    check (sys_tags <@ array['NEW','HOT','SALE','REC','TOTAL','STOCK','CUSTOM']::text[]),
  image text,
  image_url text,
  image_popup text,
  image_popup_url text,
  tab1_title text, tab1_descr text,
  tab2_title text, tab2_descr text,
  tab3_title text, tab3_descr text,
  item_settings jsonb not null default '{
    "subtitle": "", "grossMargin": 0, "orderQuotas": "", "hidePriceWhenSoldOut": false, "taxType": "TAXABLE",
    "weight": "", "dateExpired": "", "oneRawPerPiece": false, "rackBin": "", "restrictedShippingTag": "",
    "flatRateShippingWeight": "", "noticeDescr": "", "shortDescr1": "", "memberItemType": "UNLIMITED",
    "showStock": 0, "carousels": [], "priceTagForDisplay": ""
  }'::jsonb,
  theme jsonb not null default '{
    "titleTextColor": "", "titleBGColor": "", "subtitleTextColor": "", "stockPlaceholderLabel": "",
    "backOrderPlaceholderLabel": "", "customSysTagLabel": "", "itemSetStyle": "", "itemSetTopStyle": "",
    "fullCol": false, "groupbuyRetailPricesInterchanged": false
  }'::jsonb,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create index if not exists items_tenant_idx on groupbuy.items(tenant_id);
create index if not exists items_item_set_idx on groupbuy.items(item_set_id, seq);
create index if not exists items_parent_idx on groupbuy.items(parent_item_id);
create index if not exists items_tenant_uid_idx on groupbuy.items(tenant_id, uid);

-- 組合商品（新版 ItemBundleV2；/backend/ItemBundleV2/create；bundleConfig 群組→候選商品存 jsonb，同原站 JSON 結構）
create table if not exists groupbuy.item_bundles (
  id bigint generated by default as identity primary key,           -- itemBundleId / itemBundleV2Id
  tenant_id bigint not null references groupbuy.tenants(id) on delete cascade,
  group_buy_id bigint references groupbuy.group_buys(id) on delete cascade,
  group_buy_item_set_id bigint references groupbuy.group_buy_item_sets(id) on delete set null, -- 商品群組（品項）
  item_set_id bigint references groupbuy.item_sets(id) on delete set null,
  item_id bigint references groupbuy.items(id) on delete set null,   -- 代表此組合的主商品（item_type=BUNDLE_V2）
  title text not null default '',                                    -- 組合的商品名稱 inputTitle
  price numeric(14,2) not null default 0,                            -- 售價 inputPrice
  status text not null default 'DRAFT' check (status in ('DRAFT','ACTIVE')),
  bundle_type text not null default 'BUNDLE_FIXED'
    check (bundle_type in ('BUNDLE_FIXED','BUNDLE_PICK','BUNDLE_CONFIG','BUNDLE_BLIND','BUNDLE_CASCADE','BUNDLE_ROUTER')),
  display_settings jsonb not null default '{
    "invoiceShowDetail": false, "showBreakdown": false, "erpDisplayMode": "ROOT", "erpPriceAllocation": "ROOT",
    "pickingDisplayMode": "ROOT", "pickingPriceAllocation": "ROOT"
  }'::jsonb,
  bundle_config jsonb not null default '{"groups": []}'::jsonb,      -- groups[]: groupTitle,inputType(COUNTER/RADIO/CHECKBOX),minQty,maxQty,required,layout(LIST/OUTFIT_BUILDER/MATRIX_2D/MATRIX_2D_WRAP),specTitles,helperText,candidates[]
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create index if not exists item_bundles_tenant_idx on groupbuy.item_bundles(tenant_id);
create index if not exists item_bundles_group_buy_idx on groupbuy.item_bundles(group_buy_id);
create index if not exists item_bundles_item_idx on groupbuy.item_bundles(item_id);

