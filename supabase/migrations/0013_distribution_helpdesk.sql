-- 0013 銷售通路（ERP）：通路 DistributionChannel、聯絡人、通路結算單據、通路×團購、通路團購結算；客服對話 Conversation(+訊息)

create table if not exists groupbuy.distribution_channels (
  id bigint generated by default as identity primary key,           -- distributionChannelId
  tenant_id bigint not null references groupbuy.tenants(id) on delete cascade,
  channel_type text not null default 'DISTRIBUTOR' check (channel_type in ('DISTRIBUTOR','WHOLESALER','RETAILER','ECOMMERCE','KOL','INDIVIDUAL')),
  name text not null default '',
  name_alias text,
  name_short text,
  company_name text,
  company_name_alias text,
  company_vat_id text,
  tag text,
  note text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create index if not exists distribution_channels_tenant_idx on groupbuy.distribution_channels(tenant_id);

create table if not exists groupbuy.distribution_channel_contacts (
  id bigint generated by default as identity primary key,           -- distributionChannelContactId
  tenant_id bigint not null references groupbuy.tenants(id) on delete cascade,
  distribution_channel_id bigint not null references groupbuy.distribution_channels(id) on delete cascade,
  contact_type text not null default 'OFFICE' check (contact_type in ('OFFICE','ACCOUNTING','SALES')),
  name text,
  title text,
  telephone text,
  mobile text,
  email text,
  address text,
  note text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create index if not exists dcc_channel_idx on groupbuy.distribution_channel_contacts(distribution_channel_id);
create index if not exists dcc_tenant_idx on groupbuy.distribution_channel_contacts(tenant_id);

-- 通路結算單據（一張可含多團結算）
create table if not exists groupbuy.distribution_channel_transactions (
  id bigint generated by default as identity primary key,           -- distributionChannelTransactionId
  tenant_id bigint not null references groupbuy.tenants(id) on delete cascade,
  distribution_channel_id bigint not null references groupbuy.distribution_channels(id) on delete cascade,
  status text not null default 'SETTLING' check (status in ('SETTLING','REVIEWING','REVIEWED','DECLINED')),
  date_transaction timestamptz not null default now(),               -- 結算日期
  tax_rate numeric(8,2) not null default 5,
  tax_fee numeric(14,2) not null default 0,
  amount numeric(14,2) not null default 0,                           -- 結算金額
  note text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create index if not exists dct_channel_idx on groupbuy.distribution_channel_transactions(distribution_channel_id, date_transaction desc);
create index if not exists dct_tenant_idx on groupbuy.distribution_channel_transactions(tenant_id);

-- 通路 × 團購（結案階段）
create table if not exists groupbuy.distribution_channel_group_buys (
  id bigint generated by default as identity primary key,           -- distributionChannelGroupBuyId
  tenant_id bigint not null references groupbuy.tenants(id) on delete cascade,
  distribution_channel_id bigint not null references groupbuy.distribution_channels(id) on delete cascade,
  group_buy_id bigint not null references groupbuy.group_buys(id) on delete cascade,
  state text not null default 'OPEN' check (state in ('OPEN','CLOSABLE','CLOSING','CLOSED','CLOSED_NO_SALES')),
  revenue numeric(14,2) not null default 0,                          -- 分潤金額
  note text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (distribution_channel_id, group_buy_id)
);
create index if not exists dcgb_tenant_state_idx on groupbuy.distribution_channel_group_buys(tenant_id, state);
create index if not exists dcgb_group_buy_idx on groupbuy.distribution_channel_group_buys(group_buy_id);

-- 通路團購結算紀錄
create table if not exists groupbuy.distribution_channel_group_buy_transactions (
  id bigint generated by default as identity primary key,           -- distributionChannelGroupBuyTransactionId
  tenant_id bigint not null references groupbuy.tenants(id) on delete cascade,
  distribution_channel_group_buy_id bigint not null references groupbuy.distribution_channel_group_buys(id) on delete cascade,
  distribution_channel_transaction_id bigint references groupbuy.distribution_channel_transactions(id) on delete set null,
  date_transaction timestamptz not null default now(),
  gmv numeric(14,2) not null default 0,                              -- 營業額
  order_total integer not null default 0,                            -- 訂單數量
  revenue numeric(14,2) not null default 0,                          -- 分潤金額
  tax_rate numeric(8,2),
  tax_fee numeric(14,2),
  amount numeric(14,2) not null default 0,                           -- 結算金額
  note text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create index if not exists dcgbt_dcgb_idx on groupbuy.distribution_channel_group_buy_transactions(distribution_channel_group_buy_id);
create index if not exists dcgbt_dct_idx on groupbuy.distribution_channel_group_buy_transactions(distribution_channel_transaction_id);
create index if not exists dcgbt_tenant_idx on groupbuy.distribution_channel_group_buy_transactions(tenant_id);

-- 客服對話（前台「我想問問題」→ 後台 /backend/helpdesk/Conversation/list）
create table if not exists groupbuy.conversations (
  id bigint generated by default as identity primary key,           -- conversationId
  tenant_id bigint not null references groupbuy.tenants(id) on delete cascade,
  group_buy_id bigint references groupbuy.group_buys(id) on delete set null,
  sales_order_id bigint references groupbuy.sales_orders(id) on delete set null,
  customer_id bigint references groupbuy.customers(id) on delete set null,
  merchant_user_id text,                                             -- 列表「訂單編號」欄（原站鍵名）
  title text,                                                        -- 主旨
  name text,
  email text,
  telephone text,
  status text not null default 'WAITING_FOR_REPLY' check (status in ('WAITING_FOR_REPLY','REPLIED','CLOSED')),
  last_message_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create index if not exists conversations_tenant_idx on groupbuy.conversations(tenant_id, status, updated_at desc);

create table if not exists groupbuy.conversation_messages (
  id bigint generated by default as identity primary key,           -- conversationMessageId
  tenant_id bigint not null references groupbuy.tenants(id) on delete cascade,
  conversation_id bigint not null references groupbuy.conversations(id) on delete cascade,
  sender_type text not null default 'CUSTOMER' check (sender_type in ('CUSTOMER','ADMIN','SYSTEM')),
  admin_user_id bigint references groupbuy.admin_users(id) on delete set null,
  message text not null default '',
  attachments jsonb not null default '[]'::jsonb,
  is_read boolean not null default false,
  created_at timestamptz not null default now()
);
create index if not exists conversation_messages_conv_idx on groupbuy.conversation_messages(conversation_id, created_at);
create index if not exists conversation_messages_tenant_idx on groupbuy.conversation_messages(tenant_id);

