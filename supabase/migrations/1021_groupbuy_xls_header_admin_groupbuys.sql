-- groupbuy 模組（補D）：
--   1. XLS 表頭解析暫存（PARITY #124；原站 ImportExcelEditorManager → POST /ajax/XLSHeaderParser/parse.do 上傳檔案，
--      回表頭選項；之後由各匯入端點以 upload id 取回列資料）。24 小時後由讀取端略過、清理。
--   2. 團購管理員授權（PARITY #37；原站 prepareAdminUserEditor：GET /ajax/GroupBuy/adminUserGroupBuys、
--      POST /ajax/GroupBuy/update 的 adminUserGroupBuys[].adminUserId；「當管理員身份為團購受限帳戶時，只有瀏覽有授權的團購內容」）
create table if not exists groupbuy.xls_header_uploads (
  id text primary key,
  tenant_id bigint not null references groupbuy.tenants(id) on delete cascade,
  admin_user_id bigint references groupbuy.admin_users(id) on delete set null,
  filename text not null default '',
  kind text not null default 'csv',
  rows jsonb not null default '[]'::jsonb,
  created_at timestamptz not null default now()
);
create index if not exists xls_header_uploads_tenant_idx on groupbuy.xls_header_uploads(tenant_id, created_at desc);
alter table groupbuy.xls_header_uploads enable row level security;
revoke all on groupbuy.xls_header_uploads from anon, authenticated;
grant all on groupbuy.xls_header_uploads to service_role;

create table if not exists groupbuy.admin_user_group_buys (
  id bigint generated by default as identity primary key,           -- adminUserGroupBuyId
  tenant_id bigint not null references groupbuy.tenants(id) on delete cascade,
  admin_user_id bigint not null references groupbuy.admin_users(id) on delete cascade,
  group_buy_id bigint not null references groupbuy.group_buys(id) on delete cascade,
  created_at timestamptz not null default now(),
  unique (admin_user_id, group_buy_id)
);
create index if not exists admin_user_group_buys_gb_idx on groupbuy.admin_user_group_buys(tenant_id, group_buy_id);
alter table groupbuy.admin_user_group_buys enable row level security;
revoke all on groupbuy.admin_user_group_buys from anon, authenticated;
grant all on groupbuy.admin_user_group_buys to service_role;
grant usage, select on sequence groupbuy.admin_user_group_buys_id_seq to service_role;

notify pgrst, 'reload schema';
