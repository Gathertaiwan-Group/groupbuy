-- fix15：管理員登入安全性設定（系統設定 ADMIN_SECURITY_SETTINGS.rule＝IP／ALWAYS）接上登入流程。
-- admin_login_tokens：登入認證碼（只存 sha256 雜湊；明碼只出現在「待寄」的 email_messages／sms_messages，寄送未串接、不會寄出）
-- admin_ip_whitelists：rule＝IP 時認證成功的 IP 自動加入白名單（每位管理員各自一份）
-- 僅 service_role 可存取（RLS 開啟、anon/authenticated 全收回）。
create table if not exists groupbuy.admin_login_tokens (
  id bigint generated by default as identity primary key,
  tenant_id bigint not null references groupbuy.tenants(id) on delete cascade,
  admin_user_id bigint not null references groupbuy.admin_users(id) on delete cascade,
  code_hash text not null,
  ip text,
  channel text,
  attempts integer not null default 0,
  expires_at timestamptz not null,
  used_at timestamptz,
  created_at timestamptz not null default now()
);
create index if not exists admin_login_tokens_user_idx on groupbuy.admin_login_tokens(admin_user_id, created_at desc);

create table if not exists groupbuy.admin_ip_whitelists (
  id bigint generated by default as identity primary key,
  tenant_id bigint not null references groupbuy.tenants(id) on delete cascade,
  admin_user_id bigint not null references groupbuy.admin_users(id) on delete cascade,
  ip text not null,
  created_at timestamptz not null default now(),
  unique (admin_user_id, ip)
);
create index if not exists admin_ip_whitelists_tenant_idx on groupbuy.admin_ip_whitelists(tenant_id);

alter table groupbuy.admin_login_tokens enable row level security;
alter table groupbuy.admin_ip_whitelists enable row level security;
revoke all on groupbuy.admin_login_tokens, groupbuy.admin_ip_whitelists from anon, authenticated;
grant all on groupbuy.admin_login_tokens, groupbuy.admin_ip_whitelists to service_role;
grant usage, select on all sequences in schema groupbuy to service_role;
revoke all on all sequences in schema groupbuy from anon, authenticated;

notify pgrst, 'reload schema';
