-- 0012 倉儲（WMS）：倉庫 Warehouse、倉庫庫存、調撥單 WarehouseRequisition(+商品)、入庫單 Inbound(+商品)、入庫紀錄 InboundRecord、盤點

create table if not exists groupbuy.warehouses (
  id bigint generated by default as identity primary key,           -- warehouseId
  tenant_id bigint not null references groupbuy.tenants(id) on delete cascade,
  group_buy_id bigint references groupbuy.group_buys(id) on delete set null, -- 「將既有團購改作倉儲」（render=WH）
  external_id text,                                                  -- 外部編碼
  short_name text,                                                   -- 倉庫簡稱
  name text not null default '',                                     -- 倉庫名稱
  category text,                                                     -- 倉庫分類
  type text not null default 'PRIVATE' check (type in ('PRIVATE','LEASED','VIRTUAL','CHANNEL','SALES')),
  image text,
  image_url text,
  contact_person text,
  telephone text,
  mobile text,
  email text,
  country text not null default 'TW',
  postcode text,
  city text,
  district text,
  street text,
  area numeric(12,2),                                                -- 面積(坪)
  rent numeric(14,2),                                                -- 租金
  is_active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create index if not exists warehouses_tenant_idx on groupbuy.warehouses(tenant_id);

-- 倉庫 × 商品 庫存
create table if not exists groupbuy.warehouse_stocks (
  id bigint generated by default as identity primary key,
  tenant_id bigint not null references groupbuy.tenants(id) on delete cascade,
  warehouse_id bigint not null references groupbuy.warehouses(id) on delete cascade,
  item_id bigint not null references groupbuy.items(id) on delete cascade,
  quantity integer not null default 0,
  rack_bin text,
  updated_at timestamptz not null default now(),
  unique (warehouse_id, item_id)
);
create index if not exists warehouse_stocks_tenant_idx on groupbuy.warehouse_stocks(tenant_id);
create index if not exists warehouse_stocks_item_idx on groupbuy.warehouse_stocks(item_id);

-- 調撥單（/backend/WarehouseRequisition/list）
create table if not exists groupbuy.warehouse_requisitions (
  id bigint generated by default as identity primary key,           -- warehouseRequisitionId（調撥單號）
  tenant_id bigint not null references groupbuy.tenants(id) on delete cascade,
  from_warehouse_id bigint references groupbuy.warehouses(id) on delete set null, -- 來源倉
  to_warehouse_id bigint references groupbuy.warehouses(id) on delete set null,   -- 目標倉
  date_required timestamptz not null default now(),                  -- 單據日期
  date_confirmed timestamptz,
  date_transferred timestamptz,
  type text not null default 'REPLENISHMENT' check (type in ('REPLENISHMENT','INITIAL','BORROW','BACKORDER','OTHER')),
  total_amount integer not null default 0,                           -- 調撥商品總數量
  total_cost numeric(14,2) not null default 0,                       -- 調撥商品成本總額
  note text,
  from_name text, from_telephone text, from_address text,
  to_name text, to_telephone text, to_address text,
  logistic_type text not null default 'TRUCKING' check (logistic_type in ('TRUCKING','HOME_DELIVERY','SELF_PICK','EXPRESS','POSTAL','AIRWAYS','WATERWAYS')),
  requisition_status text not null default 'OPEN' check (requisition_status in ('OPEN','PENDING','APPROVED','REJECTED','TRANSFERRING','RECEIVED','CANCELLED')),
  transfer_status text not null default 'NOT_TRANSFERRED' check (transfer_status in ('NOT_TRANSFERRED','PARTLY_TRANSFERRED','COMPLETED')),
  approver text,
  requester text,
  admin_user_id bigint references groupbuy.admin_users(id) on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create index if not exists warehouse_requisitions_tenant_idx on groupbuy.warehouse_requisitions(tenant_id, date_required desc);

create table if not exists groupbuy.warehouse_requisition_items (
  id bigint generated by default as identity primary key,           -- warehouseRequisitionItemId
  tenant_id bigint not null references groupbuy.tenants(id) on delete cascade,
  warehouse_requisition_id bigint not null references groupbuy.warehouse_requisitions(id) on delete cascade,
  item_id bigint references groupbuy.items(id) on delete set null,
  uid text,
  title text,
  quantity integer not null default 0,
  transferred_quantity integer not null default 0,
  cost numeric(14,2) not null default 0,
  created_at timestamptz not null default now()
);
create index if not exists wri_req_idx on groupbuy.warehouse_requisition_items(warehouse_requisition_id);
create index if not exists wri_tenant_idx on groupbuy.warehouse_requisition_items(tenant_id);

-- 入庫單（/backend/Inbound/list）
create table if not exists groupbuy.inbounds (
  id bigint generated by default as identity primary key,           -- inboundId（入庫單號）
  tenant_id bigint not null references groupbuy.tenants(id) on delete cascade,
  warehouse_id bigint references groupbuy.warehouses(id) on delete set null, -- 入庫倉
  date_required timestamptz not null default now(),                  -- 單據日期
  status text not null default 'OPEN' check (status in ('OPEN','RECEIVED')),
  requester text,                                                    -- 入庫發起者
  note text,
  date_received timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create index if not exists inbounds_tenant_idx on groupbuy.inbounds(tenant_id, date_required desc);

create table if not exists groupbuy.inbound_items (
  id bigint generated by default as identity primary key,           -- inboundItemId
  tenant_id bigint not null references groupbuy.tenants(id) on delete cascade,
  inbound_id bigint not null references groupbuy.inbounds(id) on delete cascade,
  item_id bigint references groupbuy.items(id) on delete set null,
  sales_order_id bigint references groupbuy.sales_orders(id) on delete set null, -- importItemsFromSalesOrder
  uid text,
  title text,
  quantity integer not null default 0,
  unit_price numeric(14,2) not null default 0,
  created_at timestamptz not null default now()
);
create index if not exists inbound_items_inbound_idx on groupbuy.inbound_items(inbound_id);
create index if not exists inbound_items_tenant_idx on groupbuy.inbound_items(tenant_id);

-- 入庫紀錄（/backend/InboundRecord/list：剩餘數量、上次銷售至今天數）
create table if not exists groupbuy.inbound_records (
  id bigint generated by default as identity primary key,           -- inboundRecordId
  tenant_id bigint not null references groupbuy.tenants(id) on delete cascade,
  warehouse_id bigint references groupbuy.warehouses(id) on delete set null,
  inbound_id bigint references groupbuy.inbounds(id) on delete set null,
  item_id bigint references groupbuy.items(id) on delete set null,
  title text,
  uid text,
  date_inbound timestamptz not null default now(),                   -- 入庫日期
  unit_price numeric(14,2) not null default 0,
  quantity integer not null default 0,                               -- 入庫數量
  quantity_remaining integer not null default 0,                     -- 剩餘數量
  date_last_sale timestamptz,                                        -- 最後銷售日期
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create index if not exists inbound_records_tenant_idx on groupbuy.inbound_records(tenant_id, date_inbound);
create index if not exists inbound_records_item_idx on groupbuy.inbound_records(item_id);

-- 盤點（/backend/Warehouse/inventory；/ajax/wms/WarehouseInventory/download）
create table if not exists groupbuy.warehouse_inventories (
  id bigint generated by default as identity primary key,           -- warehouseInventoryId
  tenant_id bigint not null references groupbuy.tenants(id) on delete cascade,
  warehouse_id bigint references groupbuy.warehouses(id) on delete set null,
  group_buy_id bigint references groupbuy.group_buys(id) on delete set null,
  title text,
  status text not null default 'OPEN' check (status in ('OPEN','DONE','CANCELLED')),
  note text,
  admin_user_id bigint references groupbuy.admin_users(id) on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create index if not exists warehouse_inventories_tenant_idx on groupbuy.warehouse_inventories(tenant_id, created_at desc);

create table if not exists groupbuy.warehouse_inventory_items (
  id bigint generated by default as identity primary key,
  tenant_id bigint not null references groupbuy.tenants(id) on delete cascade,
  warehouse_inventory_id bigint not null references groupbuy.warehouse_inventories(id) on delete cascade,
  item_id bigint references groupbuy.items(id) on delete set null,
  uid text,
  title text,
  system_quantity integer not null default 0,                        -- 系統數量（可售）
  counted_quantity integer,                                          -- 實盤數量
  difference integer generated always as (coalesce(counted_quantity, system_quantity) - system_quantity) stored,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create index if not exists wii_inventory_idx on groupbuy.warehouse_inventory_items(warehouse_inventory_id);
create index if not exists wii_tenant_idx on groupbuy.warehouse_inventory_items(tenant_id);

do $$
declare t text;
begin
  foreach t in array array['warehouses','warehouse_requisitions','inbounds','inbound_records','warehouse_inventories','warehouse_inventory_items'] loop
    execute format('drop trigger if exists %I on groupbuy.%I', t || '_touch', t);
    execute format('create trigger %I before update on groupbuy.%I for each row execute function groupbuy.touch_updated_at()', t || '_touch', t);
  end loop;
  foreach t in array array['warehouses','warehouse_stocks','warehouse_requisitions','warehouse_requisition_items','inbounds','inbound_items','inbound_records','warehouse_inventories','warehouse_inventory_items'] loop
    execute format('alter table groupbuy.%I enable row level security', t);
    execute format('revoke all on groupbuy.%I from anon, authenticated', t);
    execute format('grant all on groupbuy.%I to service_role', t);
  end loop;
end $$;
grant usage, select, update on all sequences in schema groupbuy to service_role;
revoke all on all sequences in schema groupbuy from anon, authenticated;

