-- 3022 orders：加退換商品精靈「原單操作」（/backend/ReturnRefund/displayReturnAndRefund）（擁有者：orders 模組 orders-returns）
-- 原站以 HttpSession 暫存編輯中的訂單（prepare → updateOrderItem/addOrderItem 只帶單一商品，不帶訂單 id）。
-- 本系統以 orders_rr_drafts 表保存「每個後台登入 session 目前編輯中的訂單」草稿（只供畫面試算，送出時以表單內容為準）。
-- orders_rr_apply_edit(...)：送出時把表單的商品數量/單價/折價/現貨預購、運費、訂單金額寫回訂單（原子交易；庫存同步調整）。

create table if not exists groupbuy.orders_rr_drafts (
  id bigint generated by default as identity primary key,
  tenant_id bigint not null references groupbuy.tenants(id) on delete cascade,
  session_key text not null,                                          -- 後台登入 session（admin_sessions.id）
  admin_user_id bigint references groupbuy.admin_users(id) on delete set null,
  sales_order_id bigint not null references groupbuy.sales_orders(id) on delete cascade,
  payload jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create unique index if not exists orders_rr_drafts_session_key on groupbuy.orders_rr_drafts(tenant_id, session_key);
create index if not exists orders_rr_drafts_updated_idx on groupbuy.orders_rr_drafts(updated_at);
alter table groupbuy.orders_rr_drafts enable row level security;
revoke all on groupbuy.orders_rr_drafts from anon, authenticated;
grant all on groupbuy.orders_rr_drafts to service_role;
grant usage, select, update on all sequences in schema groupbuy to service_role;
revoke all on all sequences in schema groupbuy from anon, authenticated;

-- p_items：[{orderItemId(>0 既有、<0 新增), itemId, groupBuyItemSetId, price, total, discount, status('UNSHIPPING'|'BACKORDER')}]
-- 庫存：既有商品依數量增減補回/扣除（現貨/預購池依 status）；新增商品扣除；組合母項在訂單內有子項時只調整子項。
-- p_delete_empty：刪除數量為 0 的商品（自動刪除數量為0商品）。回傳 {changed, added, removed}。
create or replace function groupbuy.orders_rr_apply_edit(
  p_tenant_id bigint,
  p_order_id bigint,
  p_items jsonb,
  p_shipping_amount numeric default null,
  p_grand_total numeric default null,
  p_delete_empty boolean default false,
  p_admin_user_id bigint default null,
  p_note text default null
) returns jsonb
language plpgsql security definer set search_path = groupbuy, pg_temp as $$
declare
  o groupbuy.sales_orders%rowtype;
  l groupbuy.order_items%rowtype;
  it groupbuy.items%rowtype;
  e record;
  v_id bigint;
  v_total integer;
  v_price numeric(14,2);
  v_discount numeric(14,2);
  v_back boolean;
  v_gbis bigint;
  v_has_children boolean;
  v_stock jsonb := '[]'::jsonb;
  v_changed integer := 0;
  v_added integer := 0;
  v_removed integer := 0;
  v_seq integer;
  v_zero bigint[] := array[]::bigint[];
  v_patch jsonb := '{}'::jsonb;
begin
  select * into o from groupbuy.sales_orders where id = p_order_id and tenant_id = p_tenant_id for update;
  if not found then raise exception 'RR:訂單物件不存在'; end if;
  if o.state in ('CANCELED', 'DELETED', 'COMBINED', 'SPLITED') then
    raise exception 'RR:訂單階段為 %，不可修改商品', o.state;
  end if;
  perform set_config('groupbuy.actor', 'ADMIN', true);
  perform set_config('groupbuy.admin_user_id', coalesce(p_admin_user_id::text, ''), true);
  select coalesce(max(seq), 0) into v_seq from groupbuy.order_items where sales_order_id = o.id and tenant_id = p_tenant_id;

  for e in select value as v from jsonb_array_elements(coalesce(p_items, '[]'::jsonb)) loop
    v_id := nullif(e.v->>'orderItemId', '')::bigint;
    continue when v_id is null;
    v_total := coalesce(nullif(btrim(e.v->>'total'), '')::numeric, 0)::integer;
    v_price := coalesce(nullif(btrim(e.v->>'price'), '')::numeric, 0);
    v_discount := coalesce(nullif(btrim(e.v->>'discount'), '')::numeric, 0);
    v_back := coalesce(e.v->>'status', '') = 'BACKORDER';
    if v_total < 0 then raise exception 'RR:數量不可小於 0'; end if;
    if v_price < 0 then raise exception 'RR:單價不可小於 0'; end if;
    if v_id > 0 then
      select * into l from groupbuy.order_items where id = v_id and sales_order_id = o.id and tenant_id = p_tenant_id for update;
      if not found then raise exception 'RR:找不到訂單商品 %', v_id; end if;
      v_has_children := l.bundle_root and exists (
        select 1 from groupbuy.order_items c where c.parent_order_item_id = l.id and c.sales_order_id = o.id and c.tenant_id = p_tenant_id);
      if l.item_id is not null and not v_has_children then
        if l.back_order = v_back then
          if l.total <> v_total then
            v_stock := v_stock || jsonb_build_array(jsonb_build_object('itemId', l.item_id, 'qty', l.total - v_total, 'backOrder', l.back_order));
          end if;
        else
          v_stock := v_stock || jsonb_build_array(
            jsonb_build_object('itemId', l.item_id, 'qty', l.total, 'backOrder', l.back_order),
            jsonb_build_object('itemId', l.item_id, 'qty', -v_total, 'backOrder', v_back));
        end if;
      end if;
      if l.total <> v_total or l.price <> v_price or l.discount <> v_discount or l.back_order <> v_back then
        update groupbuy.order_items
           set total = v_total, price = v_price, discount = v_discount, back_order = v_back,
               amount = round(v_price * v_total - v_discount, 2)
         where id = l.id;
        v_changed := v_changed + 1;
      end if;
      if v_total = 0 then v_zero := v_zero || l.id; end if;
    else
      continue when v_total <= 0;
      select * into it from groupbuy.items where id = nullif(e.v->>'itemId', '')::bigint and tenant_id = p_tenant_id;
      if not found then raise exception 'RR:找不到商品 %', e.v->>'itemId'; end if;
      select g.id into v_gbis from groupbuy.group_buy_item_sets g
       where g.id = nullif(e.v->>'groupBuyItemSetId', '')::bigint and g.tenant_id = p_tenant_id;
      v_seq := v_seq + 1;
      insert into groupbuy.order_items (
        tenant_id, sales_order_id, group_buy_id, group_buy_item_set_id, item_set_id, item_id, seq, title, short_name, uid,
        price, retail_price, cprice, total, discount, amount, commission_rate, back_order, shipping_tag, state
      ) values (
        p_tenant_id, o.id, o.group_buy_id, v_gbis, it.item_set_id, it.id, v_seq, it.title, it.short_name, it.uid,
        v_price, it.price, it.cprice, v_total, v_discount, round(v_price * v_total - v_discount, 2), it.commission_rate,
        v_back, it.shipping_tag, 'UNSHIPPING'
      );
      v_stock := v_stock || jsonb_build_array(jsonb_build_object('itemId', it.id, 'qty', -v_total, 'backOrder', v_back));
      v_added := v_added + 1;
      v_gbis := null;
    end if;
  end loop;

  if p_delete_empty and array_length(v_zero, 1) > 0 then
    -- 子項先刪（母項刪除時子項會連帶刪除）
    delete from groupbuy.order_items where tenant_id = p_tenant_id and sales_order_id = o.id and id = any(v_zero) and bundle_child;
    delete from groupbuy.order_items where tenant_id = p_tenant_id and sales_order_id = o.id and id = any(v_zero);
    v_removed := array_length(v_zero, 1);
  end if;
  if jsonb_array_length(v_stock) > 0 then
    perform groupbuy.orders_adjust_item_stock(p_tenant_id, v_stock);
  end if;

  if p_shipping_amount is not null then v_patch := v_patch || jsonb_build_object('shipping_amount', p_shipping_amount); end if;
  if p_grand_total is not null then v_patch := v_patch || jsonb_build_object('grand_total', p_grand_total); end if;
  perform groupbuy.orders_admin_update(p_tenant_id, array[o.id]::bigint[], v_patch, p_admin_user_id,
    coalesce(nullif(p_note, ''), '加退換商品：原單操作'), 'ADMIN');
  return jsonb_build_object('changed', v_changed, 'added', v_added, 'removed', v_removed);
end $$;

revoke all on function groupbuy.orders_rr_apply_edit(bigint, bigint, jsonb, numeric, numeric, boolean, bigint, text) from public, anon, authenticated;
grant execute on function groupbuy.orders_rr_apply_edit(bigint, bigint, jsonb, numeric, numeric, boolean, bigint, text) to service_role;

notify pgrst, 'reload schema';
