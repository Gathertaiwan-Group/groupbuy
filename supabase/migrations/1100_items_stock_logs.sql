-- 原子庫存調整：以增量更新（避免與前台下單同時讀改寫造成超賣），回傳更新後的列。
-- 任何一個結果 < 0 時以 0 為下限（原站減少庫存不會變成負數）。
create or replace function groupbuy.items_adjust_stock(
  p_tenant_id bigint,
  p_item_id bigint,
  p_stock integer default 0,
  p_stock_available integer default 0,
  p_stock_back_order integer default 0,
  p_stock_back_order_available integer default 0,
  p_stock_cache integer default 0
) returns setof groupbuy.items
language sql
security definer
set search_path = groupbuy, pg_temp
as $$
  update groupbuy.items
     set stock = greatest(0, stock + coalesce(p_stock, 0)),
         stock_available = greatest(0, stock_available + coalesce(p_stock_available, 0)),
         stock_back_order = greatest(0, stock_back_order + coalesce(p_stock_back_order, 0)),
         stock_back_order_available = greatest(0, stock_back_order_available + coalesce(p_stock_back_order_available, 0)),
         stock_cache = greatest(0, stock_cache + coalesce(p_stock_cache, 0))
   where tenant_id = p_tenant_id and id = p_item_id
  returning *;
$$;

revoke execute on function groupbuy.items_adjust_stock(bigint, bigint, integer, integer, integer, integer, integer) from public, anon, authenticated;
grant execute on function groupbuy.items_adjust_stock(bigint, bigint, integer, integer, integer, integer, integer) to service_role;

notify pgrst, 'reload schema';
