-- 廠商資料（頂列「編輯廠商資料」，GET /ajax/Billing/show、POST /ajax/Billing/updateOne；每租戶一筆）
create table if not exists groupbuy.billings (
  id bigint generated by default as identity primary key,           -- billingId
  tenant_id bigint not null unique references groupbuy.tenants(id) on delete cascade,
  receipt_title text,                                                -- 廠商名稱
  receipt_vat_id text,                                               -- 統一編號
  telephone text,
  email text,                                                        -- 帳務信箱（逗點分隔多筆）
  country text not null default '台灣',
  postcode text,
  city text,
  district text,
  street text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

-- 月結計費方案（billingPlans；推導）
create table if not exists groupbuy.billing_plans (
  id bigint generated by default as identity primary key,           -- billingPlanId
  tenant_id bigint not null references groupbuy.tenants(id) on delete cascade,
  title text not null default '',
  billing_type text not null default 'END' check (billing_type in ('END','START','ORDERS')),
  rate numeric(8,4) not null default 0,                              -- 抽成 %
  fixed_fee numeric(14,2) not null default 0,                        -- 固定月費
  minimum_fee numeric(14,2) not null default 0,
  date_start timestamptz,
  date_end timestamptz,
  is_active boolean not null default true,
  note text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create index if not exists billing_plans_tenant_id_idx on groupbuy.billing_plans(tenant_id);

-- 月結單（/backend/BillingTransaction/list）
create table if not exists groupbuy.billing_transactions (
  id bigint generated by default as identity primary key,           -- billingTransactionId
  tenant_id bigint not null references groupbuy.tenants(id) on delete cascade,
  billing_plan_id bigint references groupbuy.billing_plans(id) on delete set null,
  billing_type text not null default 'END' check (billing_type in ('END','START','ORDERS')),
  date_transaction timestamptz not null default now(),               -- 核發日期 dateTransactionString
  period_start date,
  period_end date,
  summary jsonb not null default '{"groupBuyRevenue": 0, "groupBuys": 0, "orders": 0, "rate": 0, "fee": 0}'::jsonb,
  details jsonb not null default '[]'::jsonb,                        -- 各團購明細（展開列）
  grand_total numeric(14,2) not null default 0,                      -- 帳單金額
  tax_fee numeric(14,2) not null default 0,
  status text not null default 'UNPAID' check (status in ('UNPAID','PAID','VOID')),
  date_paid timestamptz,
  invoice_number text,
  note text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create index if not exists billing_transactions_tenant_date_idx on groupbuy.billing_transactions(tenant_id, date_transaction desc);

-- 系統設定（SystemPreference：accountSettings/einvoiceSettings/emailSettings/themeSettings…；本帳號無權限頁，推導）
create table if not exists groupbuy.system_preferences (
  id bigint generated by default as identity primary key,           -- systemPreferenceId
  tenant_id bigint not null references groupbuy.tenants(id) on delete cascade,
  name text not null,
  pref_value text,
  settings jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (tenant_id, name)
);

-- 系統通知（頂列鈴鐺 /backend/SystemNotification/list）
create table if not exists groupbuy.system_notifications (
  id bigint generated by default as identity primary key,           -- systemNotificationId
  tenant_id bigint not null references groupbuy.tenants(id) on delete cascade,
  admin_user_id bigint references groupbuy.admin_users(id) on delete cascade, -- null = 全租戶管理員
  category text not null default 'SYSTEM',
  title text not null default '',
  descr text,
  url text,
  is_read boolean not null default false,
  date_read timestamptz,
  created_at timestamptz not null default now()
);
create index if not exists system_notifications_tenant_idx on groupbuy.system_notifications(tenant_id, created_at desc);

-- 上傳檔（影片 /backend/Upload/uploadVideo、Editor upload 欄位；實體檔存 Supabase Storage）
create table if not exists groupbuy.uploads (
  id bigint generated by default as identity primary key,           -- uploadId
  tenant_id bigint not null references groupbuy.tenants(id) on delete cascade,
  category text not null default 'IMAGE' check (category in ('IMAGE','VIDEO','FILE','CSV')),
  file_name text not null default '',
  content_type text,
  size_bytes bigint,
  storage_bucket text,
  storage_path text,
  url text,
  entity text,                                                       -- 綁定的實體（GroupBuy/Item/ItemSet…）
  entity_id bigint,
  admin_user_id bigint references groupbuy.admin_users(id) on delete set null,
  created_at timestamptz not null default now()
);
create index if not exists uploads_tenant_idx on groupbuy.uploads(tenant_id, created_at desc);

-- 短網址（原站走外部 uuo.io 服務，此處自存）
create table if not exists groupbuy.short_urls (
  id bigint generated by default as identity primary key,           -- shortUrlId
  tenant_id bigint not null references groupbuy.tenants(id) on delete cascade,
  url text not null,
  short_url text not null,                                           -- 代碼
  domain text not null default 'uuo.io',
  title text,
  views integer not null default 0,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (domain, short_url)
);
create index if not exists short_urls_tenant_idx on groupbuy.short_urls(tenant_id);

