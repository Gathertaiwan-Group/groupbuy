-- 排程（/backend/Scheduler/list?entity=&foreignId=：變價排程、上下架排程）
create table if not exists groupbuy.schedulers (
  id bigint generated by default as identity primary key,           -- schedulerId
  tenant_id bigint not null references groupbuy.tenants(id) on delete cascade,
  entity text not null,                                              -- GroupBuyItemSet / Item / GroupBuy …
  foreign_id bigint not null,
  action text not null default 'ONLINE' check (action in ('ONLINE','OFFLINE','PRICE','STOCK','CUSTOM')),
  params jsonb not null default '{}'::jsonb,
  date_scheduled timestamptz not null,
  status text not null default 'PENDING' check (status in ('PENDING','DONE','FAILED','CANCELED')),
  date_executed timestamptz,
  result text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create index if not exists schedulers_tenant_idx on groupbuy.schedulers(tenant_id, entity, foreign_id);
create index if not exists schedulers_due_idx on groupbuy.schedulers(status, date_scheduled);

