create table if not exists groupbuy.sales_rules (
  id bigint generated by default as identity primary key,           -- salesRuleId
  tenant_id bigint not null references groupbuy.tenants(id) on delete cascade,
  group_buy_id bigint references groupbuy.group_buys(id) on delete cascade,
  title text not null default '',
  date_start timestamptz,                                            -- 留空白代表不限制
  date_end timestamptz,
  category text not null default 'MINIMUM_PRICE_MEET' check (category in (
    'MINIMUM_PRICE_MEET','GIFT_WITH_PURCHASE','CREDIT_CARD','CHECKOUT_MINIMUM_PRICE','MINIMUM_PIECE_CONSTRAINT',
    'MINIMUM_PIECE_MEET','MINIMUM_PIECE_MEET_MAIN_PIECE','MINIMUM_PRICE_CONSTRAINT','MINIMUM_PRICE_MEET_ITS',
    'ITEMSET_LIMITED_ITEMS','X_PIECE_ORIGINAL_PRICE_Y_DISCOUNT','ITEMSET_BUY_X_GOT_Y_FREE','ITEMSET_BUNDLE_PRICE',
    'ITEM_PRICE_MEET','TAG_MATCH','ADDITIONAL_PURCHASE','ADDITIONAL_PURCHASE_OPTIONAL',
    'ADDITIONAL_PURCHASE_MINIMUM_PRICE_MEET','ADDITIONAL_PURCHASE_MINIMUM_PRICE_MEET_OPTIONAL',
    'GIFT_MINIMUM_PRICE_MEET_TOTAL_PAID','GIFT_MINIMUM_PRICE_MEET_NO_PICK_TOTAL_PAID','GIFT_MINIMUM_PRICE_MEET',
    'GIFT_MINIMUM_PRICE_MEET_NO_PICK','GIFT_MINIMUM_PIECE_MEET','GIFT_MINIMUM_PIECE_MEET_NO_PICK','GIFT_LOTTERY',
    'ITEM_BUY_X_GOT_Y_FREE','ITEM_EXCLUDED','ITEM_PACKAGE',
    -- 精靈模式卡片代碼（modal-salesrule-wizard）
    'MINIMUM_PRICE_MEET_ITS_ITEM_TAG','MINIMUM_PRICE_MEET_ITS_PACK_DISCOUNT','TAG_MATCH_1','TAG_MATCH_2',
    'ADDITIONAL_PURCHASE_MINIMUM_PRICE_MEET_ITEM')),
  dollar_or_percentage text not null default 'DOLLAR' check (dollar_or_percentage in (
    'DOLLAR','PERCENTAGE','POINT','SALE_PRICE','PERCENTAGE_RETAIL_PRICE','PIECE','PACK_DOLLAR','PACK_SALE_PRICE',
    'DOLLAR_PACK_DISCOUNT','BUNDLE_PRICE')),
  discount numeric(14,2) not null default 0,
  minimum numeric(14,2) not null default 0,                          -- 最小單位
  max_apply_times integer not null default -1,                       -- 最多套用次數（-1 不限）
  available_quota integer not null default 100000,                   -- 可供優惠數量
  used_quota integer not null default 0,                             -- 已使用數量（推導統計）
  priority integer not null default 1,
  smart_priority boolean not null default false,
  tag text,                                                          -- 優惠標籤（| 分隔）
  exclude_tag text,                                                  -- 不合併計算標籤（| 分隔）
  main_item_type text not null default 'ANY' check (main_item_type in ('ANY','INSTOCK','BACKORDER')),
  apply_to_group_buy boolean not null default false,                 -- 可跨品項合併
  hidden boolean not null default false,                             -- 隱藏不顯示標籤
  combinable boolean not null default false,                         -- 可合併計算(用於滿額贈)
  is_active boolean not null default true,                           -- 啟用/停用
  sales_rule_settings jsonb not null default '{
    "seq": null, "giftMandatory": false, "repeatMinimumString": "", "tieredMinimumsString": "",
    "giftTagRule": "ALL", "tagMatchRule": "ALL", "maxDiscountAmount": "", "minDiscountTotalPrice": "",
    "includedPostcodes": "", "priceSortOrder": "", "packRule": {"rule": "", "subItemTotal": ""}, "erp": {}
  }'::jsonb,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create index if not exists sales_rules_tenant_idx on groupbuy.sales_rules(tenant_id);
create index if not exists sales_rules_group_buy_idx on groupbuy.sales_rules(group_buy_id, priority);

