-- 4500 倉儲（WMS）：庫存異動帳（ledger）＋交易性庫存函式（入庫／調撥／盤點／出貨歸檔）＋盤點匯入暫存。
-- 擁有者：warehouse 模組。只動 groupbuy schema；不改 items 等既有表結構。
--
-- 庫存模型（依 docs/DATA_MODEL.md）：
--   倉庫實體庫存 = groupbuy.warehouse_stocks(warehouse_id, item_id).quantity
--   商品可售庫存 = groupbuy.items.stock / stock_available（由 items/orders/storefront 維護）
--   入庫、盤點調整會同時調整倉庫庫存與商品 stock/stock_available（同一交易）；調撥只在倉庫之間移轉（商品總量不變）。
--   每一筆倉庫庫存異動都寫 groupbuy.warehouse_stock_movements（異動前後數量、來源單據、操作者），可追溯。
-- 所有函式 security definer、只授權 service_role；錯誤訊息以「WMS:」開頭（應用層轉成 400 提示）。

-- ───────────────────────── 庫存異動帳 ─────────────────────────
create table if not exists groupbuy.warehouse_stock_movements (
  id bigint generated by default as identity primary key,
  tenant_id bigint not null references groupbuy.tenants(id) on delete cascade,
  warehouse_id bigint references groupbuy.warehouses(id) on delete set null,
  item_id bigint references groupbuy.items(id) on delete set null,
  uid text,
  title text,
  movement_type text not null check (movement_type in ('INBOUND','TRANSFER_OUT','TRANSFER_IN','INVENTORY','INVENTORY_BACKORDER','ARCHIVE')),
  quantity_change integer not null,
  quantity_before integer not null,
  quantity_after integer not null,
  item_stock_before integer,
  item_stock_after integer,
  item_stock_available_before integer,
  item_stock_available_after integer,
  source_type text,          -- INBOUND｜WAREHOUSE_REQUISITION｜WAREHOUSE_INVENTORY
  source_id bigint,
  note text,
  admin_user_id bigint references groupbuy.admin_users(id) on delete set null,
  actor text,
  created_at timestamptz not null default now()
);
create index if not exists warehouse_stock_movements_tenant_idx on groupbuy.warehouse_stock_movements(tenant_id, created_at desc);
create index if not exists warehouse_stock_movements_item_idx on groupbuy.warehouse_stock_movements(tenant_id, item_id, warehouse_id);
create index if not exists warehouse_stock_movements_source_idx on groupbuy.warehouse_stock_movements(tenant_id, source_type, source_id);
alter table groupbuy.warehouse_stock_movements enable row level security;
revoke all on groupbuy.warehouse_stock_movements from anon, authenticated;
grant all on groupbuy.warehouse_stock_movements to service_role;

