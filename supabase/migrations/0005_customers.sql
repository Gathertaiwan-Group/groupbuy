-- 0005 前台會員（Customer）與會員制度：會員方案 RoyaltyProgram、會員卡 LoyaltyCard、地址簿、FB 身分、點數、黑名單、前台 session

-- 會員方案（RoyaltyProgram；優惠條件/優惠卷「會員身份」、商品會員價 ItemRoyaltyProgram）
create table if not exists groupbuy.royalty_programs (
  id bigint generated by default as identity primary key,           -- royaltyProgramId
  tenant_id bigint not null references groupbuy.tenants(id) on delete cascade,
  title text not null default '',
  descr text,
  price numeric(14,2) not null default 0,                            -- 方案費用（item_type=RP 商品）
  duration_days integer,                                             -- 有效天數（null=永久）
  discount_rate numeric(8,2) not null default 0,
  point_rate numeric(8,2) not null default 0,
  seq integer not null default 0,
  is_active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create index if not exists royalty_programs_tenant_idx on groupbuy.royalty_programs(tenant_id);

-- 會員卡（LoyaltyCard；item_type=LOYALTY_CARD）
create table if not exists groupbuy.loyalty_cards (
  id bigint generated by default as identity primary key,           -- loyaltyCardId
  tenant_id bigint not null references groupbuy.tenants(id) on delete cascade,
  title text not null default '',
  descr text,
  card_number_prefix text,
  price numeric(14,2) not null default 0,
  is_active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create index if not exists loyalty_cards_tenant_idx on groupbuy.loyalty_cards(tenant_id);

-- 前台會員（登入帳號可用 email / 電話 / 會員ID；密碼 6–10 碼，只存 bcrypt hash）
create table if not exists groupbuy.customers (
  id bigint generated by default as identity primary key,           -- customerId（＝會員ID）
  tenant_id bigint not null references groupbuy.tenants(id) on delete cascade,
  uuid text not null default replace(gen_random_uuid()::text, '-', ''),
  email text,
  telephone text,
  firstname text,
  birthday date,                                                     -- birthdayString
  password_hash text,
  is_activated boolean not null default false,
  activate_method text not null default 'EMAIL' check (activate_method in ('EMAIL','SMS')),
  activation_token text,
  date_activated timestamptz,
  reset_password_token text,
  date_reset_password_expires timestamptz,
  royalty_program_id bigint references groupbuy.royalty_programs(id) on delete set null,
  date_royalty_program_expires timestamptz,
  loyalty_card_id bigint references groupbuy.loyalty_cards(id) on delete set null,
  loyalty_card_number text,
  points integer not null default 0,                                 -- 目前點數餘額（由 point_transactions 累計）
  tags text,
  note text,
  daily_order_limits integer,                                        -- 會員每日下單數量上限
  last_login_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create index if not exists customers_tenant_idx on groupbuy.customers(tenant_id);
create unique index if not exists customers_tenant_email_key on groupbuy.customers(tenant_id, lower(email)) where email is not null and email <> '';
create index if not exists customers_tenant_telephone_idx on groupbuy.customers(tenant_id, telephone);
create unique index if not exists customers_uuid_key on groupbuy.customers(uuid);

-- 前台會員 session（id = token 的 sha256 hex）
create table if not exists groupbuy.customer_sessions (
  id text primary key,
  tenant_id bigint not null references groupbuy.tenants(id) on delete cascade,
  customer_id bigint not null references groupbuy.customers(id) on delete cascade,
  expires_at timestamptz not null,
  user_agent text,
  ip text,
  created_at timestamptz not null default now()
);
create index if not exists customer_sessions_customer_idx on groupbuy.customer_sessions(customer_id);
create index if not exists customer_sessions_tenant_idx on groupbuy.customer_sessions(tenant_id);

-- 會員地址簿（/ajax/web/CustomerAddress/*，ep.widget.address）
create table if not exists groupbuy.customer_addresses (
  id bigint generated by default as identity primary key,           -- customerAddressId
  tenant_id bigint not null references groupbuy.tenants(id) on delete cascade,
  customer_id bigint not null references groupbuy.customers(id) on delete cascade,
  uuid text not null default replace(gen_random_uuid()::text, '-', ''),
  firstname text,
  telephone text,
  email text,
  country text not null default 'TW',
  postcode text,
  city text,
  district text,
  street text,
  cvs_type text check (cvs_type is null or cvs_type in ('','UNIMART','FAMI','FAMI_FROZEN','PICKUP')),
  cvs_store_id text,
  cvs_store_name text,
  cvs_address text,
  is_default boolean not null default false,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create index if not exists customer_addresses_customer_idx on groupbuy.customer_addresses(customer_id);
create index if not exists customer_addresses_tenant_idx on groupbuy.customer_addresses(tenant_id);

-- Facebook 身分（訂單 customerFacebook{name,pictureUrl}、報表授權 facebookAuth.name、前台 FB 快速登入）
create table if not exists groupbuy.facebook_auths (
  id bigint generated by default as identity primary key,           -- facebookAuthId
  tenant_id bigint not null references groupbuy.tenants(id) on delete cascade,
  customer_id bigint references groupbuy.customers(id) on delete set null,
  facebook_id text,
  name text,
  email text,
  picture_url text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create index if not exists facebook_auths_tenant_idx on groupbuy.facebook_auths(tenant_id);
create index if not exists facebook_auths_customer_idx on groupbuy.facebook_auths(customer_id);

-- 點數異動（PointTransaction；訂單徽章 -點/+點：reason='USE_POINT' 為扣點）
create table if not exists groupbuy.point_transactions (
  id bigint generated by default as identity primary key,           -- pointTransactionId
  tenant_id bigint not null references groupbuy.tenants(id) on delete cascade,
  customer_id bigint references groupbuy.customers(id) on delete cascade,
  sales_order_id bigint,                                             -- FK 於 0010 建立
  reason text not null default 'ADD_POINT'
    check (reason in ('USE_POINT','ADD_POINT','REFUND_POINT','RETURN_POINT','EXPIRE_POINT','ADJUST_POINT','RANDOM_POINT')),
  points integer not null default 0,
  balance_after integer,
  note text,
  date_expired timestamptz,
  created_at timestamptz not null default now()
);
create index if not exists point_transactions_tenant_idx on groupbuy.point_transactions(tenant_id);
create index if not exists point_transactions_customer_idx on groupbuy.point_transactions(customer_id);
create index if not exists point_transactions_order_idx on groupbuy.point_transactions(sales_order_id);

-- 黑名單（/backend/Blacklist/list）
create table if not exists groupbuy.blacklists (
  id bigint generated by default as identity primary key,           -- blacklistId
  tenant_id bigint not null references groupbuy.tenants(id) on delete cascade,
  type text not null default 'BLOCK_PAYMENT' check (type in ('BLOCK_PAYMENT','SILENT_BLOCK')),
  firstname text,
  email text,
  telephone text,
  ip text,
  note text,
  log text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create index if not exists blacklists_tenant_idx on groupbuy.blacklists(tenant_id);
create index if not exists blacklists_telephone_idx on groupbuy.blacklists(tenant_id, telephone);
create index if not exists blacklists_email_idx on groupbuy.blacklists(tenant_id, lower(email));

