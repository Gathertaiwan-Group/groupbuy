-- 說明中心文章（Post；/jranv、/ajax/web/Post/lookup）
create table if not exists groupbuy.posts (
  id bigint generated by default as identity primary key,           -- postId
  tenant_id bigint not null references groupbuy.tenants(id) on delete cascade,
  group_buy_id bigint references groupbuy.group_buys(id) on delete cascade,
  web_menu_node_id bigint references groupbuy.web_menu_nodes(id) on delete set null,
