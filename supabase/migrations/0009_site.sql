-- 0009 進階設定與官網：進階設定 GroupBuyPreference（key/value）＋設定鍵目錄、團購標籤套用（GroupBuyTagGroupBuy）、
--      官網 HomeView / HomeViewSection / HomeViewItem / Lookbook、網站選單 WebMenu、說明中心文章 Post、系統公告 News

-- 進階設定鍵目錄（全平台共用；原站本團 0 筆，鍵名/型態為推導，見 docs/DATA_MODEL.md）
create table if not exists groupbuy.preference_definitions (
  name text primary key,                                             -- 設定鍵（如 EINVOICE_PROVIDER）
  display_name text not null,                                        -- 欄位名稱（分類按鈕依前綴篩選：前台-、分潤、系統信…）
  category text not null default 'OTHER' check (category in ('FRONTEND','COMMISSION','CUSTOM','EMAIL','EINVOICE','SUBSCRIPTION','OTHER')),
  field_type text not null default 'text' check (field_type in ('text','textarea','select','checkbox','ckeditor','ckeditor5','number','settings')),
  options_key text,                                                  -- 列表 API options 的鍵（同名，如 EINVOICE_PROVIDER）
  default_value text,
  level integer not null default 1,                                  -- 1=團購層級，0=租戶層級
  seq integer not null default 0,
  descr text,
  created_at timestamptz not null default now()
);

-- 進階設定值（/backend/GroupBuyPreference/list?groupBuyId=；group_buy_id null = 租戶預設，group_buy_tag_id = 標籤範本設定）
create table if not exists groupbuy.group_buy_preferences (
  id bigint generated by default as identity primary key,           -- groupBuyPreferenceId
  tenant_id bigint not null references groupbuy.tenants(id) on delete cascade,
  group_buy_id bigint references groupbuy.group_buys(id) on delete cascade,
  group_buy_tag_id bigint references groupbuy.group_buy_tags(id) on delete cascade,
  name text not null,
  level integer not null default 1,
  field_type text not null default 'text',
  display_name text,
  pref_value text,                                                   -- 內容（ckeditor 型亦存此欄）
  group_buy_preference_settings jsonb not null default '{}'::jsonb,  -- 專用編輯器的子設定（THEME_SETTINGS、ACTIVITY_POPUP_SETTINGS…）
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create index if not exists gbp_tenant_idx on groupbuy.group_buy_preferences(tenant_id);
create index if not exists gbp_group_buy_idx on groupbuy.group_buy_preferences(group_buy_id);
create unique index if not exists gbp_scope_name_key on groupbuy.group_buy_preferences(tenant_id, coalesce(group_buy_id, 0), coalesce(group_buy_tag_id, 0), name);

-- 團購 × 團購標籤（套用設定範本；/ajax/GroupBuyTagGroupBuy/save|delete）
create table if not exists groupbuy.group_buy_tag_group_buys (
  id bigint generated by default as identity primary key,           -- groupBuyTagGroupBuyId
  tenant_id bigint not null references groupbuy.tenants(id) on delete cascade,
  group_buy_tag_id bigint not null references groupbuy.group_buy_tags(id) on delete cascade,
  group_buy_id bigint not null references groupbuy.group_buys(id) on delete cascade,
  created_at timestamptz not null default now(),
  unique (group_buy_tag_id, group_buy_id)
);
create index if not exists gbtgb_tenant_idx on groupbuy.group_buy_tag_group_buys(tenant_id);
create index if not exists gbtgb_group_buy_idx on groupbuy.group_buy_tag_group_buys(group_buy_id);

-- 網站選單（WebMenu）與節點（MenuTree；說明中心 /jranv/menu/4411/所有教學）
create table if not exists groupbuy.web_menus (
  id bigint generated by default as identity primary key,           -- webMenuId
  tenant_id bigint not null references groupbuy.tenants(id) on delete cascade,
  group_buy_id bigint references groupbuy.group_buys(id) on delete cascade,
  title text not null default '',
  category text not null default 'TOP' check (category in ('TOP','SIDE','FOOTER','CUSTOM')),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create index if not exists web_menus_tenant_idx on groupbuy.web_menus(tenant_id);

create table if not exists groupbuy.web_menu_nodes (
  id bigint generated by default as identity primary key,           -- webMenuNodeId（menu/{id}/{title}）
  tenant_id bigint not null references groupbuy.tenants(id) on delete cascade,
  web_menu_id bigint references groupbuy.web_menus(id) on delete cascade,
  parent_id bigint references groupbuy.web_menu_nodes(id) on delete cascade,
  title text not null default '',
  url text,
  seq integer not null default 0,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
