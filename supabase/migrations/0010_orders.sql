create or replace function groupbuy.log_sales_order_history() returns trigger
language plpgsql set search_path = groupbuy, pg_temp as $$
begin
  if tg_op = 'INSERT' then
    insert into groupbuy.sales_order_histories (tenant_id, sales_order_id, state_to, status_to, action, actor, note)
    values (new.tenant_id, new.id, new.state, new.status, new.action,
            coalesce(nullif(current_setting('groupbuy.actor', true), ''), 'SYSTEM'), '建立訂單');
  elsif new.state is distinct from old.state or new.status is distinct from old.status
        or (new.action is distinct from old.action and new.action <> 'NONE') then
    insert into groupbuy.sales_order_histories (tenant_id, sales_order_id, state_from, state_to, status_from, status_to, action, actor,
                                                admin_user_id)
    values (new.tenant_id, new.id, old.state, new.state, old.status, new.status, new.action,
            coalesce(nullif(current_setting('groupbuy.actor', true), ''), 'SYSTEM'),
            nullif(current_setting('groupbuy.admin_user_id', true), '')::bigint);
  end if;
  return null;
end $$;
drop trigger if exists sales_orders_history on groupbuy.sales_orders;
create trigger sales_orders_history after insert or update on groupbuy.sales_orders
  for each row execute function groupbuy.log_sales_order_history();

