-- 0100 core：後台登入紀錄（登入失敗次數限制＋登入日誌）
-- 只動 groupbuy schema。依賴 0002_core_auth（tenants、admin_users）。
create table if not exists groupbuy.admin_login_attempts (
  id bigint generated by default as identity primary key,
  account text not null,                                   -- 嘗試登入的帳號（原樣，可能不存在）
  admin_user_id bigint references groupbuy.admin_users(id) on delete set null,
  tenant_id bigint references groupbuy.tenants(id) on delete set null,
  ip text,
  user_agent text,
  success boolean not null,
  reason text,                                             -- 失敗原因：BAD_PASSWORD / NO_ACCOUNT / INACTIVE / LOCKED
  created_at timestamptz not null default now()
);
create index if not exists admin_login_attempts_account_idx on groupbuy.admin_login_attempts (account, created_at desc);
create index if not exists admin_login_attempts_ip_idx on groupbuy.admin_login_attempts (ip, created_at desc);
create index if not exists admin_login_attempts_tenant_idx on groupbuy.admin_login_attempts (tenant_id, created_at desc);

alter table groupbuy.admin_login_attempts enable row level security;
revoke all on groupbuy.admin_login_attempts from anon, authenticated;
grant all on groupbuy.admin_login_attempts to service_role;
grant usage, select on all sequences in schema groupbuy to service_role;
revoke all on all sequences in schema groupbuy from anon, authenticated;

notify pgrst, 'reload schema';
