-- 團購 × 關鍵字標籤 關聯（addTag/removeTag/addBatchTagging/getAssociatedGroupBuys）
create table if not exists groupbuy.group_buy_sys_tags (
  id bigint generated by default as identity primary key,
  tenant_id bigint not null references groupbuy.tenants(id) on delete cascade,
  group_buy_id bigint not null references groupbuy.group_buys(id) on delete cascade,
  group_buy_sys_tag_ref_id bigint not null references groupbuy.group_buy_sys_tag_refs(id) on delete cascade,
  created_at timestamptz not null default now(),
  unique (group_buy_id, group_buy_sys_tag_ref_id)
);
create index if not exists group_buy_sys_tags_tenant_id_idx on groupbuy.group_buy_sys_tags(tenant_id);
create index if not exists group_buy_sys_tags_ref_idx on groupbuy.group_buy_sys_tags(group_buy_sys_tag_ref_id);

create or replace function groupbuy.sync_sys_tag_ref_count() returns trigger
language plpgsql set search_path = groupbuy, pg_temp as $$
begin
  if tg_op in ('INSERT','UPDATE') then
    update groupbuy.group_buy_sys_tag_refs r
       set group_buy_count = (select count(*) from groupbuy.group_buy_sys_tags t where t.group_buy_sys_tag_ref_id = r.id),
           usage_count = r.usage_count + case when tg_op = 'INSERT' then 1 else 0 end,
           last_used_at = now()
     where r.id = new.group_buy_sys_tag_ref_id;
  end if;
  if tg_op in ('DELETE','UPDATE') then
    update groupbuy.group_buy_sys_tag_refs r
       set group_buy_count = (select count(*) from groupbuy.group_buy_sys_tags t where t.group_buy_sys_tag_ref_id = r.id)
     where r.id = old.group_buy_sys_tag_ref_id;
  end if;
  return null;
end $$;
drop trigger if exists group_buy_sys_tags_count on groupbuy.group_buy_sys_tags;
create trigger group_buy_sys_tags_count after insert or update or delete on groupbuy.group_buy_sys_tags
  for each row execute function groupbuy.sync_sys_tag_ref_count();

