-- 團購關鍵字標籤字典（/backend/GroupBuySysTagRef/list；列表「新增標籤」tag-manager 也用這裡的標籤）
create table if not exists groupbuy.group_buy_sys_tag_refs (
  id bigint generated by default as identity primary key,           -- groupBuySysTagRefId
  tenant_id bigint not null references groupbuy.tenants(id) on delete cascade,
