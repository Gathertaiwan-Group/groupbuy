-- 最新消息／常見問題（News?tag=NEWS|FAQ）
alter table groupbuy.news add column if not exists tag text not null default 'NEWS';
alter table groupbuy.news add column if not exists seq integer not null default 0;
alter table groupbuy.news add column if not exists categories text[] not null default '{}';
do $$ begin
  if not exists (select 1 from pg_constraint where conname = 'news_tag_check' and conrelid = 'groupbuy.news'::regclass) then
    alter table groupbuy.news add constraint news_tag_check check (tag in ('NEWS','FAQ'));
  end if;
end $$;
create index if not exists news_group_buy_tag_idx on groupbuy.news(group_buy_id, tag);

-- 橫幅／小圖／Lookbook
alter table groupbuy.lookbooks add column if not exists tag text;
alter table groupbuy.lookbooks add column if not exists date_start timestamptz;
alter table groupbuy.lookbooks add column if not exists date_end timestamptz;
alter table groupbuy.lookbooks add column if not exists image_path text;
alter table groupbuy.lookbooks add column if not exists link_category text not null default 'EXTERNAL_LINK';
alter table groupbuy.lookbooks add column if not exists link_url text;
alter table groupbuy.lookbooks add column if not exists reference text;
alter table groupbuy.lookbooks add column if not exists settings jsonb not null default '{}'::jsonb;
alter table groupbuy.lookbooks add column if not exists updated_at timestamptz not null default now();
create index if not exists lookbooks_group_buy_idx on groupbuy.lookbooks(group_buy_id, category, seq);
drop trigger if exists lookbooks_touch on groupbuy.lookbooks;
create trigger lookbooks_touch before update on groupbuy.lookbooks for each row execute function groupbuy.touch_updated_at();

-- 文章
alter table groupbuy.posts add column if not exists seq integer not null default 0;
alter table groupbuy.posts add column if not exists status text not null default 'PUBLISH';
alter table groupbuy.posts add column if not exists post_type text not null default 'NORMAL';
alter table groupbuy.posts add column if not exists access_level text;
alter table groupbuy.posts add column if not exists author text;
alter table groupbuy.posts add column if not exists image_url text;
alter table groupbuy.posts add column if not exists category_tag_ids bigint[] not null default '{}';
alter table groupbuy.posts add column if not exists settings jsonb not null default '{}'::jsonb;
update groupbuy.posts set status = case when is_published then 'PUBLISH' else 'DRAFT' end
  where status is distinct from case when is_published then 'PUBLISH' else 'DRAFT' end;
do $$ begin
  if not exists (select 1 from pg_constraint where conname = 'posts_status_check' and conrelid = 'groupbuy.posts'::regclass) then
    alter table groupbuy.posts add constraint posts_status_check check (status in ('DRAFT','PUBLISH','FUTURE','TRASH'));
  end if;
  if not exists (select 1 from pg_constraint where conname = 'posts_post_type_check' and conrelid = 'groupbuy.posts'::regclass) then
    alter table groupbuy.posts add constraint posts_post_type_check check (post_type in ('NORMAL','PREMIUM'));
  end if;
end $$;
create index if not exists posts_group_buy_idx on groupbuy.posts(group_buy_id, seq);

-- 文章分類（PostCategory）
create table if not exists groupbuy.post_categories (
  id bigint generated by default as identity primary key,           -- postCategoryId
  tenant_id bigint not null references groupbuy.tenants(id) on delete cascade,
  group_buy_id bigint references groupbuy.group_buys(id) on delete cascade,
  title text not null default '',
  tag text not null default '',
  seq integer not null default 0,
  settings jsonb not null default '{"postSortType":"DATE_POST_DES"}'::jsonb, -- postCategorySettings
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create index if not exists post_categories_tenant_idx on groupbuy.post_categories(tenant_id);
create index if not exists post_categories_group_buy_idx on groupbuy.post_categories(group_buy_id);
drop trigger if exists post_categories_touch on groupbuy.post_categories;
create trigger post_categories_touch before update on groupbuy.post_categories for each row execute function groupbuy.touch_updated_at();
alter table groupbuy.post_categories enable row level security;
revoke all on groupbuy.post_categories from anon, authenticated;
grant all on groupbuy.post_categories to service_role;
grant usage, select on all sequences in schema groupbuy to service_role;

notify pgrst, 'reload schema';
