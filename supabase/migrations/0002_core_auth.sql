-- 0002 核心：租戶、後台管理員、後台 session
-- 共用庫：只動 groupbuy schema。主鍵 bigint identity（by default，方便示範資料指定原站 id）。

create table if not exists groupbuy.tenants (
  id bigint generated by default as identity primary key,
  code text unique not null,               -- 原站 groupBuyAccount（路徑前綴，如 guest_ep）
  name text,
  created_at timestamptz default now()
);

create table if not exists groupbuy.admin_users (
  id bigint generated by default as identity primary key,
  tenant_id bigint not null references groupbuy.tenants(id) on delete cascade,
  account text unique not null,            -- 登入帳號（顯示為 [租戶]帳號）
  password_hash text not null,             -- bcrypt
  display_name text,
  role text,                               -- ADMIN / STAFF ...（原站未擷取，推導）
  permissions jsonb default '{}'::jsonb,   -- 權限旗標（系統設定、csv編輯器、退款單據 等）
  is_active boolean default true,
  last_login_at timestamptz,
  created_at timestamptz default now()
);
create index if not exists admin_users_tenant_id_idx on groupbuy.admin_users(tenant_id);

create table if not exists groupbuy.admin_sessions (
  id text primary key,                     -- session token 的 sha256 hex
  admin_user_id bigint references groupbuy.admin_users(id) on delete cascade,
  tenant_id bigint references groupbuy.tenants(id) on delete cascade,
  expires_at timestamptz not null,
  user_agent text,
  ip text,
  created_at timestamptz default now()
);
create index if not exists admin_sessions_admin_user_id_idx on groupbuy.admin_sessions(admin_user_id);
create index if not exists admin_sessions_tenant_id_idx on groupbuy.admin_sessions(tenant_id);
create index if not exists admin_sessions_expires_at_idx on groupbuy.admin_sessions(expires_at);

-- 通用：updated_at 觸發器（業務表的 dateModified 樂觀鎖用）
create or replace function groupbuy.touch_updated_at() returns trigger
language plpgsql set search_path = groupbuy, pg_temp as $$
begin
  new.updated_at := now();
  return new;
end $$;

-- 安全：RLS + 只給 service_role
alter table groupbuy.tenants enable row level security;
alter table groupbuy.admin_users enable row level security;
alter table groupbuy.admin_sessions enable row level security;
revoke all on groupbuy.tenants, groupbuy.admin_users, groupbuy.admin_sessions from anon, authenticated;
grant all on groupbuy.tenants, groupbuy.admin_users, groupbuy.admin_sessions to service_role;
grant usage, select, update on all sequences in schema groupbuy to service_role;
revoke all on all sequences in schema groupbuy from anon, authenticated;
revoke all on function groupbuy.touch_updated_at() from public, anon, authenticated;
grant execute on function groupbuy.touch_updated_at() to service_role;

