-- groupbuy 模組（gapfill 子任務 B）：臉書型團購「臉書社團」（/backend/FbGroup/show）綁定的社團與貼文模板。
-- Facebook 未串接：綁定只寫入本地紀錄（不驗證 accessToken、不呼叫 Graph API）；貼文模板（feedTemplate）照存。
-- 推導：原站資料表未擷取，欄位依 public/scripts/fb.js 使用的鍵（fbGroupId、groupId、name、feedTemplate、expired、pageId、pageName）。
create table if not exists groupbuy.fb_groups (
  id bigint generated by default as identity primary key,           -- fbGroupId
  tenant_id bigint not null references groupbuy.tenants(id) on delete cascade,
  group_buy_id bigint not null references groupbuy.group_buys(id) on delete cascade,
  group_id text not null default '',                                -- 臉書社團 id（groupId）
  name text not null default '',                                    -- 社團名稱
  feed_template text not null default '',                           -- 貼文模板
  select_page boolean not null default false,                       -- 綁定時是否另選粉專（selectPage）
  page_id text,                                                     -- 粉專 id（FbPage/bind，未串接）
  page_name text,
  expired boolean not null default false,                           -- 授權已過期
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create unique index if not exists fb_groups_group_buy_uidx on groupbuy.fb_groups(tenant_id, group_buy_id);

drop trigger if exists fb_groups_touch on groupbuy.fb_groups;
create trigger fb_groups_touch before update on groupbuy.fb_groups for each row execute function groupbuy.touch_updated_at();

alter table groupbuy.fb_groups enable row level security;
revoke all on groupbuy.fb_groups from anon, authenticated;
grant all on groupbuy.fb_groups to service_role;
grant usage, select on sequence groupbuy.fb_groups_id_seq to service_role;

notify pgrst, 'reload schema';
