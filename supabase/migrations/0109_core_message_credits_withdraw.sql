-- fix20 續：寄送扣點、範本內容旗標、取消入帳撤回已排入的付款成功信
-- 1) email_messages.content_final：true＝內容已由管理員確認（後台「寄信」編輯器送出），寄送時不再套用系統信範本
-- 2) Email／簡訊餘額扣點（帳務設定 ACCOUNT_SETTINGS.creditEmail／creditSms；月結單頁顯示同一個值）
--    message_credit_ledger：每筆訊息最多一列（channel＋message_id 唯一）→ 不重扣
--    delivery_credit_reserve()：寄送前鎖住帳務設定列，餘額足夠才先預扣（RESERVED）；未設定餘額（null）＝不計點
--    delivery_credit_settle()：寄出成功 → CHARGED（確定扣點）；寄送失敗 → 退回點數（RELEASED）。只處理 RESERVED 的列（冪等）
--    結果：只有寄出成功的訊息會被扣點；並行寄送也不會扣成負數
-- 3) accounting_revert_bank_transaction()：取消入帳時，付款成功通知信若仍為「未串接」或「已排入未取走」（QUEUED）→ 撤回（FAILED）；
--    寄送中／已寄出 → 無法撤回，回應訊息與 mailWithdraw 欄位說明。其餘邏輯與 3501 相同。
-- 僅 service_role 可執行／存取。

alter table groupbuy.email_messages add column if not exists content_final boolean not null default false;

create table if not exists groupbuy.message_credit_ledger (
  id bigint generated by default as identity primary key,
  tenant_id bigint not null references groupbuy.tenants(id) on delete cascade,
  channel text not null check (channel in ('EMAIL','SMS')),
  message_id bigint not null,
  points integer not null check (points > 0),
  status text not null check (status in ('RESERVED','CHARGED','RELEASED')),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (channel, message_id)
);
create index if not exists message_credit_ledger_tenant_idx on groupbuy.message_credit_ledger(tenant_id, created_at desc);
alter table groupbuy.message_credit_ledger enable row level security;
revoke all on groupbuy.message_credit_ledger from anon, authenticated;
grant all on groupbuy.message_credit_ledger to service_role;
grant usage, select, update on all sequences in schema groupbuy to service_role;
revoke all on all sequences in schema groupbuy from anon, authenticated;

-- 帳務設定 json（settings 優先，否則 pref_value）
create or replace function groupbuy.delivery_account_settings_json(p_settings jsonb, p_pref_value text)
returns jsonb language plpgsql immutable set search_path = groupbuy, pg_temp as $$
begin
  if p_settings is not null and jsonb_typeof(p_settings) = 'object' then return p_settings; end if;
  begin
    if p_pref_value is not null and jsonb_typeof(p_pref_value::jsonb) = 'object' then return p_pref_value::jsonb; end if;
  exception when others then
    return '{}'::jsonb;
  end;
  return '{}'::jsonb;
end $$;

create or replace function groupbuy.delivery_credit_reserve(p_tenant_id bigint, p_channel text, p_message_id bigint, p_points integer)
returns jsonb
language plpgsql security definer set search_path = groupbuy, pg_temp as $$
declare
  sp groupbuy.system_preferences%rowtype;
  j jsonb;
  k text := case when p_channel = 'SMS' then 'creditSms' else 'creditEmail' end;
  raw text;
  bal numeric;
  led groupbuy.message_credit_ledger%rowtype;
begin
  if p_channel not in ('EMAIL','SMS') or coalesce(p_points, 0) <= 0 then
    return jsonb_build_object('result', 'INVALID');
  end if;
  select * into sp from groupbuy.system_preferences
   where tenant_id = p_tenant_id and name = 'ACCOUNT_SETTINGS' for update;
  if not found then return jsonb_build_object('result', 'UNMETERED'); end if;
  j := groupbuy.delivery_account_settings_json(sp.settings, sp.pref_value);
  raw := btrim(coalesce(j->>k, ''));
  if raw !~ '^-?\d+(\.\d+)?$' then return jsonb_build_object('result', 'UNMETERED'); end if;
  bal := raw::numeric;
  select * into led from groupbuy.message_credit_ledger where channel = p_channel and message_id = p_message_id for update;
  if found and led.status in ('RESERVED','CHARGED') then
    return jsonb_build_object('result', 'ALREADY', 'balance', bal, 'status', led.status);
  end if;
  if bal < p_points then
    return jsonb_build_object('result', 'INSUFFICIENT', 'balance', bal, 'points', p_points);
  end if;
  j := jsonb_set(j, array[k], to_jsonb(bal - p_points));
  update groupbuy.system_preferences set settings = j, pref_value = j::text, updated_at = now() where id = sp.id;
  if led.id is not null then
    update groupbuy.message_credit_ledger set status = 'RESERVED', points = p_points, tenant_id = p_tenant_id, updated_at = now() where id = led.id;
  else
    insert into groupbuy.message_credit_ledger (tenant_id, channel, message_id, points, status) values (p_tenant_id, p_channel, p_message_id, p_points, 'RESERVED');
  end if;
  return jsonb_build_object('result', 'RESERVED', 'balance', bal - p_points, 'points', p_points);
end $$;

create or replace function groupbuy.delivery_credit_settle(p_channel text, p_message_id bigint, p_success boolean)
returns jsonb
language plpgsql security definer set search_path = groupbuy, pg_temp as $$
declare
  led groupbuy.message_credit_ledger%rowtype;
  sp groupbuy.system_preferences%rowtype;
  j jsonb;
  k text := case when p_channel = 'SMS' then 'creditSms' else 'creditEmail' end;
  raw text;
begin
  select * into led from groupbuy.message_credit_ledger where channel = p_channel and message_id = p_message_id for update;
  if not found or led.status <> 'RESERVED' then return jsonb_build_object('result', 'NOOP'); end if;
  if p_success then
    update groupbuy.message_credit_ledger set status = 'CHARGED', updated_at = now() where id = led.id;
    return jsonb_build_object('result', 'CHARGED', 'points', led.points);
  end if;
  select * into sp from groupbuy.system_preferences where tenant_id = led.tenant_id and name = 'ACCOUNT_SETTINGS' for update;
  if found then
    j := groupbuy.delivery_account_settings_json(sp.settings, sp.pref_value);
    raw := btrim(coalesce(j->>k, ''));
    if raw ~ '^-?\d+(\.\d+)?$' then
      j := jsonb_set(j, array[k], to_jsonb(raw::numeric + led.points));
      update groupbuy.system_preferences set settings = j, pref_value = j::text, updated_at = now() where id = sp.id;
    end if;
  end if;
  update groupbuy.message_credit_ledger set status = 'RELEASED', updated_at = now() where id = led.id;
  return jsonb_build_object('result', 'RELEASED', 'points', led.points);
end $$;

revoke all on function groupbuy.delivery_account_settings_json(jsonb, text) from public, anon, authenticated;
revoke all on function groupbuy.delivery_credit_reserve(bigint, text, bigint, integer) from public, anon, authenticated;
revoke all on function groupbuy.delivery_credit_settle(text, bigint, boolean) from public, anon, authenticated;
grant execute on function groupbuy.delivery_account_settings_json(jsonb, text) to service_role;
grant execute on function groupbuy.delivery_credit_reserve(bigint, text, bigint, integer) to service_role;
grant execute on function groupbuy.delivery_credit_settle(text, bigint, boolean) to service_role;

create or replace function groupbuy.accounting_revert_bank_transaction(
  p_tenant_id bigint, p_bank_transaction_id bigint, p_admin_user_id bigint
) returns jsonb
language plpgsql set search_path = groupbuy, pg_temp as $$
declare
  bt groupbuy.bank_transactions%rowtype;
  so groupbuy.sales_orders%rowtype;
  c groupbuy.bank_transaction_confirmations%rowtype;
  v_mail_status text;
  v_mail text := null;
  v_mail_note text := '';
begin
  select * into bt from groupbuy.bank_transactions
   where id = p_bank_transaction_id and tenant_id = p_tenant_id for update;
  if not found then
    return jsonb_build_object('ok', false, 'code', 'NOT_FOUND', 'message', '找不到匯款明細');
  end if;
  select * into c from groupbuy.bank_transaction_confirmations
   where tenant_id = p_tenant_id and bank_transaction_id = bt.id and reverted_at is null for update;
  if not found then
    return jsonb_build_object('ok', false, 'code', 'NOT_CONFIRMED', 'message', '此明細尚未入帳');
  end if;
  select * into so from groupbuy.sales_orders
   where id = c.sales_order_id and tenant_id = p_tenant_id for update;
  if not found then
    return jsonb_build_object('ok', false, 'code', 'ORDER_NOT_FOUND', 'message', '找不到對應的訂單');
  end if;
  -- 入帳後訂單只要有任何異動（含取消訂單、改金額、出貨）就不自動還原
  if so.state not in ('NEW', 'PROCESSING')
     or so.status is distinct from c.new_status
     or so.total_paid <> c.prev_total_paid + c.amount
     or (c.order_updated_at is not null and so.updated_at is distinct from c.order_updated_at) then
    return jsonb_build_object('ok', false, 'code', 'ORDER_CHANGED', 'uuid', so.uuid,
      'message', '訂單 ' || so.uuid || ' 入帳後已有其他異動，無法自動取消入帳，請至訂單管理處理');
  end if;
  if exists (select 1 from groupbuy.refund_requisitions r
              where r.tenant_id = p_tenant_id and r.sales_order_id = so.id and r.status in ('PENDING', 'APPROVED', 'REFUNDED')) then
    return jsonb_build_object('ok', false, 'code', 'HAS_REFUND', 'uuid', so.uuid,
      'message', '訂單 ' || so.uuid || ' 已有退款單據（待審核／已核准／已退款），無法取消入帳');
  end if;

  perform set_config('groupbuy.actor', 'ADMIN', true);
  perform set_config('groupbuy.admin_user_id', coalesce(p_admin_user_id::text, ''), true);

  update groupbuy.sales_orders
     set total_paid = c.prev_total_paid,
         date_paid = c.prev_date_paid,
         status = c.prev_status
   where id = so.id and tenant_id = p_tenant_id;

  update groupbuy.bank_transaction_confirmations
     set reverted_at = now(), reverted_by = p_admin_user_id
   where id = c.id;

  if c.email_message_id is not null then
    -- 未串接或已排入但尚未被寄送取走（QUEUED）→ 撤回；寄送取件是 status='QUEUED' 的條件式更新，列鎖保證兩者只有一個成功
    update groupbuy.email_messages
       set status = 'FAILED', error_message = '已取消入帳（撤回，未寄出）', next_attempt_at = null, updated_at = now()
     where id = c.email_message_id and tenant_id = p_tenant_id and status in ('NOT_SENT_UNINTEGRATED', 'QUEUED');
    if found then
      v_mail := 'WITHDRAWN';
      v_mail_note := '；付款成功通知信已撤回（未寄出）';
    else
      select status into v_mail_status from groupbuy.email_messages where id = c.email_message_id and tenant_id = p_tenant_id;
      if v_mail_status = 'SENT' then
        v_mail := 'ALREADY_SENT';
        v_mail_note := '；付款成功通知信已寄出，無法撤回，請另行通知顧客';
      elsif v_mail_status = 'SENDING' then
        v_mail := 'SENDING';
        v_mail_note := '；付款成功通知信寄送中，無法撤回，請確認寄送結果後另行通知顧客';
      else
        v_mail := coalesce(v_mail_status, 'NOT_FOUND');
      end if;
    end if;
  end if;

  -- 明細不再佔用訂單：若要重新入帳，請以「指定訂單編號」重新匯入
  update groupbuy.bank_transactions
     set checked = false, sales_order_id = null,
         status = '已取消入帳（原對應訂單 ' || so.uuid || '）'
   where id = bt.id and tenant_id = p_tenant_id;

  return jsonb_build_object('ok', true, 'code', 'REVERTED', 'salesOrderId', so.id, 'uuid', so.uuid, 'mailWithdraw', v_mail,
    'message', '訂單 ' || so.uuid || ' 已取消入帳，付款狀態已還原' || v_mail_note);
end $$;

revoke all on function groupbuy.accounting_revert_bank_transaction(bigint, bigint, bigint) from public, anon, authenticated;
grant execute on function groupbuy.accounting_revert_bank_transaction(bigint, bigint, bigint) to service_role;

