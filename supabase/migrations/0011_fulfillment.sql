--      金流交易紀錄 SalesOrderTransaction、退款單據 RefundRequisition、銷退紀錄 SalesReturnRecord、預購轉現貨紀錄、寄信/簡訊紀錄

-- 出貨匯出批次（/backend/ShippingRecord/export、月份紀錄 shipped）
create table if not exists groupbuy.shipping_records (
  id bigint generated by default as identity primary key,           -- shippingRecordId
  tenant_id bigint not null references groupbuy.tenants(id) on delete cascade,
  group_buy_id bigint references groupbuy.group_buys(id) on delete set null,
  shipping_tag_id bigint references groupbuy.shipping_tags(id) on delete set null,
  tag text,                                                          -- 標籤（可編輯）
  purpose text not null default 'SHIP' check (purpose in ('SHIP','EXPORT_ONLY')), -- 出貨(更新為已出貨) / 回壓訂單(不更新)
  shipping_provider text,                                            -- 匯出格式
  shipping_type text check (shipping_type is null or shipping_type in ('NORMAL','PICKUP','CVS','INTL','NOD','HK_SF')),
  back_order smallint not null default -1 check (back_order in (-1,0,1,2)), -- 不限/只有現貨/只有預購/同時有
  send_shipping_email boolean not null default false,
  date_expected_shipping date,
  date_expected_shipping_back_order date,
  filter jsonb not null default '{}'::jsonb,                         -- 匯出時的篩選條件
  file_name text,
  file_url text,
  order_count integer not null default 0,
  item_count integer not null default 0,
  state text not null default 'EXPORTED' check (state in ('EXPORTED','COMPLETED')), -- 隱藏已完成出貨
  admin_user_id bigint references groupbuy.admin_users(id) on delete set null,
  date_exported timestamptz not null default now(),                  -- 匯出日期 / 出貨月份
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create index if not exists shipping_records_tenant_idx on groupbuy.shipping_records(tenant_id, date_exported desc);

create table if not exists groupbuy.shipping_record_orders (
  id bigint generated by default as identity primary key,
  tenant_id bigint not null references groupbuy.tenants(id) on delete cascade,
  shipping_record_id bigint not null references groupbuy.shipping_records(id) on delete cascade,
  sales_order_id bigint not null references groupbuy.sales_orders(id) on delete cascade,
  created_at timestamptz not null default now(),
  unique (shipping_record_id, sales_order_id)
);
create index if not exists sro_order_idx on groupbuy.shipping_record_orders(sales_order_id);
create index if not exists sro_tenant_idx on groupbuy.shipping_record_orders(tenant_id);

-- 超商/物流/自取追蹤（SalesOrderCVSTrace：超商未取、自取未取、超時出貨）
create table if not exists groupbuy.sales_order_cvs_traces (
  id bigint generated by default as identity primary key,           -- salesOrderCVSTraceId
  tenant_id bigint not null references groupbuy.tenants(id) on delete cascade,
  sales_order_id bigint not null references groupbuy.sales_orders(id) on delete cascade,
  group_buy_id bigint references groupbuy.group_buys(id) on delete set null,
  status text not null default 'UNSHIPPING' check (status in ('UNSHIPPING','UNARRIVED','PICKING','SHIPPING','SHIPPED','ARRIVED','UNPICKED','PICKED','RETURNED','RETURNING')),
  tracking_number text,                                              -- 貨運單號
  cvs_type text,
  cvs_store_id text,
  cvs_store_name text,
  date_arrived timestamptz,                                          -- 到店日期
  date_picked timestamptz,
  date_returning timestamptz,
  date_returned timestamptz,
  date_notified timestamptz,                                         -- 最近通知日期
