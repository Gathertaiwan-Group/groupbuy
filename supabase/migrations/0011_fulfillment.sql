create index if not exists socvs_tenant_status_idx on groupbuy.sales_order_cvs_traces(tenant_id, status);

-- 電子發票（Invoice；含作廢、折讓）
create table if not exists groupbuy.invoices (
  id bigint generated by default as identity primary key,           -- invoiceId
  tenant_id bigint not null references groupbuy.tenants(id) on delete cascade,
  sales_order_id bigint references groupbuy.sales_orders(id) on delete set null,
  group_buy_id bigint references groupbuy.group_buys(id) on delete set null,
  merchant_order_id text,                                            -- 發票訂單號碼
  invoice_status text not null default 'SEND_EINVOICE' check (invoice_status in ('SEND_EINVOICE','PENDING_EINVOICE','EINVOICE_SENT','EINVOICE_FAILED','INVALIDATE_EINVOICE','EINVOICE_INVALIDATED','SEND_CANCELED','SEND_ALLOWANCE','ALLOWANCE_SENT','ALLOWANCE_FAILED')),
  provider text not null default 'NONE',                             -- EINVOICE_PROVIDER
  invoice_number text,
  random_number text,                                                -- 隨機碼
  amount numeric(14,2) not null default 0,                           -- 發票金額
  sales_amount numeric(14,2),
  tax_amount numeric(14,2),
  tax_type text not null default 'TAXABLE' check (tax_type in ('TAXABLE','ZERO_TAX_RATE','TAX_EXEMPT','MIX')),
  buyer_vat_id text,
  buyer_title text,
  carrier_type smallint check (carrier_type is null or carrier_type in (0,1,2,3)),
  carrier_num text,
  donation_code text,
  print_flag boolean not null default false,
  items jsonb not null default '[]'::jsonb,
  date_einvoice timestamptz,                                         -- 開立時間（或預約時間）
  date_invalidated timestamptz,
  invalid_reason text,
  allowance_number text,
  allowance_amount numeric(14,2),
  date_allowance timestamptz,
  allowance_reason text,
  error_message text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create index if not exists invoices_tenant_idx on groupbuy.invoices(tenant_id, date_einvoice desc);
create index if not exists invoices_order_idx on groupbuy.invoices(sales_order_id);
create index if not exists invoices_group_buy_idx on groupbuy.invoices(group_buy_id);

